#!/usr/bin/env python3
"""Find the canons in data/canons/corpus.json: for every ordered pair of voices (leader, follower), the
transformation, time lag and interval under which the follower repeats the leader, and how strictly.

Transformations: rectus; inversus (contrary motion: the follower's diatonic step is c - the leader's);
augmentation and diminution by 2 (each with or without inversion); retrograde (cancrizans) and
retrograde inversion. A candidate (lag, offset) is voted for by every pair of notes, one in each voice,
whose durations stand in the transformation's ratio; the most voted wins. Strictness is then measured
note by note:

  coverage   share of the leader's notes (in the span the follower can answer) found in the follower
             at the transformed time and diatonic step
  exact      of those, the share at the same chromatic interval too (real, not merely diatonic, imitation)
  breaks     the bars where the imitation lapses (free notes, an altered note, the free ending)

Writes data/canons/canons.json and docs/canons/CATALOGUE.md. A reading, not an authority: its first test
is whether it finds the interval each piece's title names (see CATALOGUE.md)."""
import json
from collections import Counter, defaultdict
from fractions import Fraction as F
from pathlib import Path

CORPUS = Path("data/canons/corpus.json")
OUT = Path("data/canons/canons.json")
DOC = Path("docs/canons/CATALOGUE.md")

TRANSFORMS = {
    # name: (time factor, inverted, retrograde)
    "rectus": (F(1), False, False),
    "inversus": (F(1), True, False),
    "augmentation": (F(2), False, False),
    "augmentation, inverted": (F(2), True, False),
    "diminution": (F(1, 2), False, False),
    "diminution, inverted": (F(1, 2), True, False),
    "retrograde": (F(1), False, True),
    "retrograde inversion": (F(1), True, True),
}
NAMES = {0: "unison", 1: "second", 2: "third", 3: "fourth", 4: "fifth", 5: "sixth", 6: "seventh", 7: "octave",
         8: "ninth", 9: "tenth", 10: "eleventh", 11: "twelfth", 12: "thirteenth", 13: "fourteenth", 14: "double octave"}


def interval_name(d: int) -> str:
    a = abs(d)
    base = NAMES.get(a, f"{a + 1}th")
    return base if d == 0 else f"{base} {'above' if d > 0 else 'below'}"


def main_line(v):
    return [n for n in v if not n.get("chord")]


def image(n, t):
    fac, inv, retro = TRANSFORMS[t]
    on, dur = F(n["on"]).limit_denominator(96), F(n["dur"]).limit_denominator(96)
    if retro:
        return -(on + dur), dur, (-n["step"] if inv else n["step"]), (-n["midi"] if inv else n["midi"])
    return on * fac, dur * fac, (-n["step"] if inv else n["step"]), (-n["midi"] if inv else n["midi"])


def fits(A, B, t, n=6):
    """The n most voted (lag, step offset) mapping leader A onto follower B under transformation t."""
    votes = Counter()
    bdur = defaultdict(list)
    for b in B:
        bdur[F(b["dur"]).limit_denominator(96)].append(b)
    for a in A:
        on, dur, st, _ = image(a, t)
        for b in bdur.get(dur, ()):
            lag = F(b["on"]).limit_denominator(96) - on
            if not TRANSFORMS[t][2] and lag <= 0:
                continue
            votes[(lag, b["step"] - st)] += 1
    return [(lag, k, v) for (lag, k), v in votes.most_common(n)]


def measure(A, B, t, lag, k, length):
    bmap = {(F(b["on"]).limit_denominator(96), b["step"]): b for b in B}
    bstart = min(F(b["on"]).limit_denominator(96) for b in B)
    res = []
    for a in A:
        on, dur, st, mi = image(a, t)
        ton = on + lag
        if ton < bstart or ton >= F(length).limit_denominator(96):
            continue
        b = bmap.get((ton, st + k))
        res.append((a, ton, b, (b is not None and b["midi"] - mi) if b is not None else None))
    return res


def bar_of(on, bars):
    n = bars[0]["n"]
    for b in bars:
        if b["on"] <= on + 1e-9:
            n = b["n"]
    return n


def main() -> None:
    corpus = json.loads(CORPUS.read_text())
    out = {}
    lines = ["# Bach's canons: the catalogue as read from the score", "",
             "Generated by `python3 tools/canons/detect.py` from `data/canons/corpus.json` (sources: "
             "`data/sources/bach-canons/SOURCE.md`). One row per canonic pair of voices found: the leader, the follower, "
             "the transformation, the time interval (lag, in the piece's beats and bars), the interval of imitation "
             "(diatonic; for contrary motion, the interval between the first two corresponding notes), and how strict the "
             "imitation is: *coverage* is the share of the leader's notes that the follower answers at the right time and "
             "diatonic step, *exact* the share of those that also keep the chromatic interval (a canon at the second, third, "
             "sixth or seventh cannot be exact everywhere and stay in the key), *breaks* the bars where the imitation lapses.",
             "", "A reading by program: the check that it reads correctly is whether it finds the interval each title names "
             "(column *title says*).", ""]
    for pid, pc in corpus.items():
        voices = {vid: main_line(v) for vid, v in pc["voices"].items()}
        found = []
        for a_id, A in voices.items():
            if len(A) < 6:
                continue
            # the follower may move between staves: look for it among all the other voices' notes
            B = [dict(n, vid=v_id) for v_id, V in voices.items() if v_id != a_id for n in V]
            if len(B) < 6:
                continue
            for t in TRANSFORMS:
                for lag, k, v in fits(A, B, t):
                    if v < 10:
                        continue
                    m = measure(A, B, t, lag, k, pc["length"])
                    hit = [x for x in m if x[2] is not None]
                    if len(hit) < 12 or len(hit) / max(1, len(m)) < 0.5:
                        continue
                    cov = len(hit) / len(m)
                    exact_offset = Counter(x[3] for x in hit).most_common(1)[0][0]
                    exact = sum(1 for x in hit if x[3] == exact_offset) / len(hit)
                    first = hit[0]
                    entry = first[2]["step"] - first[0]["step"]
                    miss_bars = sorted({bar_of(float(x[1]), pc["bars"]) for x in m if x[2] is None})
                    fv = Counter(x[2]["vid"] for x in hit)
                    found.append({"leader": a_id, "follower": "+".join(v for v, _ in fv.most_common()), "transform": t,
                                  "lag_q": float(lag), "offset": k, "entry_steps": entry, "semitones": exact_offset,
                                  "matched": len(hit), "span": len(m), "coverage": round(cov, 3), "exact": round(exact, 3),
                                  "from_bar": bar_of(float(hit[0][1]), pc["bars"]), "to_bar": bar_of(float(hit[-1][1]), pc["bars"]),
                                  "breaks": miss_bars})
        # drop a relation whose matched notes are mostly another, stronger relation's (the same imitation seen
        # through a different voice id or transformation); keep the rest, strongest first
        rows = []
        for f in sorted(found, key=lambda f: (-f["matched"], list(TRANSFORMS).index(f["transform"]))):
            same = [r for r in rows if r["transform"] == f["transform"] and r["lag_q"] == f["lag_q"] and r["offset"] == f["offset"]]
            mirror = [r for r in rows if r["leader"] in f["follower"].split("+") and f["leader"] in r["follower"].split("+")
                      and r["transform"] == f["transform"] and abs(r["lag_q"]) == abs(f["lag_q"])]
            if same or mirror:
                continue
            rows.append(f)
        out[pid] = {"title": pc["title"], "set": pc["set"], "meter": pc["meter"], "bars": len(pc["bars"]), "canons": rows,
                    "free": [v for v in voices if not any(v in (r["leader"], r["follower"]) for r in rows)]}
    OUT.write_text(json.dumps(out, indent=1))
    # the document
    beat = {"12/8": 1.5, "9/8": 1.5, "6/8": 1.5, "3/8": 0.5, "9/16": 0.75, "2/2": 2}
    lines += ["| piece | title says | leader → follower | transformation | lag | interval read | coverage | exact | breaks (bars) | free voices |",
              "|---|---|---|---|---|---|---|---|---|---|"]
    for pid, r in out.items():
        pc = corpus[pid]
        barlen = pc["bars"][1]["on"] - pc["bars"][0]["on"] if len(pc["bars"]) > 1 else 4
        b = beat.get(pc["meter"], 1)
        if not r["canons"]:
            lines.append(f"| {pid} | {r['title']} | none found | | | | | | | {', '.join(r['free'])} |")
            continue
        for i, c in enumerate(r["canons"]):
            lag = c["lag_q"]
            lagtxt = f"{lag / b:g} beats ({lag / barlen:g} bars)" if c["transform"] not in ("retrograde", "retrograde inversion") else "—"
            br = c["breaks"]
            brtxt = ", ".join(map(str, br[:12])) + (" …" if len(br) > 12 else "")
            lines.append(f"| {pid if i == 0 else ''} | {r['title'] if i == 0 else ''} | {c['leader']} → {c['follower']} (bars {c['from_bar']}–{c['to_bar']}) | {c['transform']} | "
                         f"{lagtxt} | {interval_name(c['entry_steps'])} ({c['semitones'] if c['transform'] in ('rectus', 'augmentation', 'diminution') else '±'} semitones) | "
                         f"{c['coverage']:.0%} ({c['matched']}/{c['span']}) | {c['exact']:.0%} | {brtxt} | {', '.join(r['free']) if i == 0 else ''} |")
    DOC.parent.mkdir(parents=True, exist_ok=True)
    DOC.write_text("\n".join(lines) + "\n")
    print("\n".join(lines[-80:]))


if __name__ == "__main__":
    main()
