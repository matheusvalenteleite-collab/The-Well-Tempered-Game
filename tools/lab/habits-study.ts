const data = Object.fromEntries(CHOICE_SPECIES.map((s) => [s, collect(s)])) as Record<SpeciesId, ReturnType<typeof collect>>;
const pooled = (f: (d: ReturnType<typeof collect>) => Score) => {
  const per = CHOICE_SPECIES.map((s) => f(data[s]));
  const free = per.reduce((a, x) => a + x.free, 0);
  return { per, bits: per.reduce((a, x) => a + x.bits * x.free, 0) / free, top: per.reduce((a, x) => a + x.top, 0), free };
};
