import { loadFuxRepository } from "../../src/music/fux/load-node.ts";
import { contextFor } from "../../src/counterpoint/choices/audit.ts";
import { choicesAt } from "../../src/counterpoint/choices/alternatives.ts";
import { CHOICE_SPECIES, choiceUnits, fuxLines, onsets, type FuxLine } from "../../src/counterpoint/choices/corpus.ts";
import { ALL_FEATURES, arrival, featureBits, learnFeatures, type Feature, type FeatureInput } from "../../src/counterpoint/choices/features.ts";
