const uniform = pooled((d) => evaluate(d, () => 0));
out.push(row("no model (every legal pitch alike)", uniform));
const current = pooled((d) => {
  const hab = d.lines.map((_, li) => buildHabits(d.lines.filter((__, j) => j !== li), d.lines[0].species));
  return evaluate(d, (li, x) => {
    const h = legacyHabitOf(hab[li], x.cantusVoice, x.layout, x.cantus, x.line, x.unit);
    return h.melodic + h.vertical;
  });
});
out.push(row("the Lab's model so far (melodic by role, vertical, successive downbeats)", current));

let chosen: Feature[] = [];
let best = uniform;
const steps: string[] = [];
for (;;) {
  let pick: Feature | null = null;
  let pickScore = best;
  for (const f of ALL_FEATURES.filter((x) => !chosen.includes(x))) {
    const r = pooled((d) => withFeatures(d, [...chosen, f]));
    if (r.bits < pickScore.bits - 0.01) {
      pick = f;
      pickScore = r;
    }
  }
  if (!pick) break;
  chosen = [...chosen, pick];
  best = pickScore;
  out.push(row(`+ ${pick.label} (summed)`, best));
  steps.push(pick.id);
}

/*
 * Weighted: the features overlap (the motion into a downbeat partly repeats the interval it
 * arrives at), so summing their surprisals counts the same evidence twice. A choice model learns
 * one weight per feature: P(pitch) ∝ 2^(-Σ w_f · bits_f). The feature tables are learnt without
 * the exercise judged, and so are the weights (fitted on the other exercises, all species pooled).
 */
interface Row {
  species: SpeciesId;
  li: number;
  /** x[c][f]: bits of feature f for legal candidate c; fux: index of Fux's note. */
  x: number[][];
  fux: number;
}
const rows: Row[] = [];
for (const s of CHOICE_SPECIES) {
  const d = data[s];
  const tables = d.lines.map((_, li) => learnFeatures(d.lines.filter((__, j) => j !== li), ALL_FEATURES, unitsOf));
  for (const c of d.choices) {
    if (c.legal.length < 2) continue;
    const l = d.lines[c.li];
    const x = c.legal.map((p) => {
      const input: FeatureInput = { layout: l.layout, cantus: l.cantus, line: trial(l, c.unit, p), cantusVoice: l.cantusVoice, unit: c.unit };
      return ALL_FEATURES.map((f) => featureBits(tables[c.li], [f], input));
    });
    rows.push({ species: s, li: c.li, x, fux: c.legal.indexOf(c.fux) });
  }
}
const F = ALL_FEATURES.length;
const LN2 = Math.LN2;
/** Mean negative log-likelihood (bits) of Fux's choices under weights w. */
function nll(w: number[], rs: Row[]): number {
  let t = 0;
  for (const r of rs) {
    const e = r.x.map((xc) => -LN2 * xc.reduce((a, v, f) => a + w[f] * v, 0));
    const m = Math.max(...e);
    const z = e.reduce((a, v) => a + Math.exp(v - m), 0);
    t += (m + Math.log(z) - e[r.fux]) / LN2;
  }
  return t / rs.length;
}
/** Weights ≥ 0 by projected gradient descent, a little L2 shrinkage. */
function fit(rs: Row[], mask: boolean[] = Array(F).fill(true)): number[] {
  let w = mask.map((m) => (m ? 0.3 : 0));
  const lambda = 0.002;
  for (let it = 0; it < 400; it++) {
    const g = Array(F).fill(0);
    for (const r of rs) {
      const e = r.x.map((xc) => -LN2 * xc.reduce((a, v, f) => a + w[f] * v, 0));
      const m = Math.max(...e);
      const ex = e.map((v) => Math.exp(v - m));
      const z = ex.reduce((a, v) => a + v, 0);
      for (let f = 0; f < F; f++) {
        let exp = 0;
        for (let c = 0; c < r.x.length; c++) exp += (ex[c] / z) * r.x[c][f];
        g[f] += r.x[r.fux][f] - exp;
      }
    }
    w = w.map((wf, f) => (mask[f] ? Math.max(0, wf - (0.5 * g[f]) / rs.length - lambda * wf) : 0));
  }
  return w;
}
/** Leave-one-exercise-out: weights fitted without the exercise, judged on it (per species when asked). */
function crossValidated(mask: boolean[], perSpecies = false) {
  const per = new Map<SpeciesId, { bits: number; top: number; free: number }>();
  for (const s of CHOICE_SPECIES) per.set(s, { bits: 0, top: 0, free: 0 });
  const groups = new Map<string, Row[]>();
  for (const r of rows) {
    const k = `${r.species}:${r.li}`;
    if (!groups.has(k)) groups.set(k, []);
    groups.get(k)!.push(r);
  }
  for (const [k, test] of groups) {
    const w = fit(rows.filter((r) => `${r.species}:${r.li}` !== k && (!perSpecies || r.species === test[0].species)), mask);
    for (const r of test) {
      const acc = per.get(r.species)!;
      acc.bits += nll(w, [r]);
      acc.free++;
      const cost = r.x.map((xc) => xc.reduce((a, v, f) => a + w[f] * v, 0));
      const min = Math.min(...cost);
      if (cost[r.fux] === min && cost.filter((c) => c === min).length === 1) acc.top++;
    }
  }
  const list = CHOICE_SPECIES.map((s) => {
    const a = per.get(s)!;
    return { bits: a.bits / a.free, top: a.top, free: a.free };
  });
  const free = list.reduce((a, x) => a + x.free, 0);
  return { per: list, bits: list.reduce((a, x) => a + x.bits * x.free, 0) / free, top: list.reduce((a, x) => a + x.top, 0), free };
}
