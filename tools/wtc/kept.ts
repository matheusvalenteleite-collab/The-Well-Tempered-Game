// Where the subject ends by what Bach keeps (the owner's criterion (a), D163): for each fugue, the opening voice's
// line from the subject's first note on (the settled subject and a dozen notes beyond it) set against every later
// statement the analysis finds; for each statement, how many notes it follows the opening, interval by interval
// (diatonic steps, an octave's displacement allowed, one mismatch allowed in the first three intervals for a tonal
// head). The subject by criterion (a): the longest opening that most later statements keep. Statements that keep
// less than half the settled subject (heads, false entries) are left out. Writes docs/wtc/KEPT.md.
// Usage: node tools/wtc/kept.ts
import { readFileSync, writeFileSync } from "node:fs";
import type { WtcPiece } from "../../src/wtc/corpus.ts";
import { keptLength, line, TPQ } from "../../src/wtc/fugue.ts";
import { fugueOf } from "../../src/wtc/library.ts";

const pieces = [...(JSON.parse(readFileSync("data/wtc/fugues.json", "utf8")) as WtcPiece[]), ...(JSON.parse(readFileSync("data/wtc/more.json", "utf8")) as WtcPiece[])];
const settled = (JSON.parse(readFileSync("data/wtc/subjects-settled.json", "utf8")) as { fugues: Record<string, { voice: number; subject: [number, number, string][] }> }).fugues;
const EXTRA = 12;

const name = (id: string) => (id.startsWith("wtc") ? `${id[3] === "1" ? "I" : "II"}/${Number(id.slice(5))}` : id);
const rows: string[] = [];
const differ: string[] = [];
for (const p of pieces) {
  const st = settled[p.id];
  if (!st) continue;
  const lf = fugueOf(p);
  const first = p.bars.find((b) => b.n === 1)?.on ?? 0;
  const pad = first / TPQ > 1e-6 ? lf.barQuarters - first / TPQ : 0;
  const [mn, md] = p.meter.split("/").map(Number);
  const bar = (mn * 4 * TPQ) / md;
  const beat = (4 * TPQ) / md;
  const where = (t: number) => `${Math.floor((t - first) / bar) + 1}:${+(1 + (t - first - (Math.floor((t - first) / bar)) * bar) / beat).toFixed(2)}`;
  const n = st.subject.length;
  const opening = line(p.voices[st.voice]).filter((x) => x.on >= st.subject[0][0]);
  const ref = opening.slice(0, n + EXTRA).map((x) => x.pitch);
  const kept: { at: string; k: number }[] = [];
  for (const e of lf.entries) {
    if (e.inverted) continue;
    const v = lf.voice[e.notes[0]];
    const on = Math.round((e.at - pad) * TPQ);
    if (v === st.voice && Math.abs(on - st.subject[0][0]) < TPQ / 4) continue; // the opening itself
    const l = line(p.voices[v]).filter((x) => x.on >= on - TPQ / 8).slice(0, ref.length).map((x) => x.pitch);
    const k = keptLength(ref, l);
    if (k >= Math.ceil(n / 2)) kept.push({ at: `v${v} ${where(on)}`, k });
  }
  if (!kept.length) continue;
  // The longest opening kept by most statements.
  let L = 1;
  for (let len = 1; len <= ref.length; len++) if (kept.filter((x) => x.k >= len).length * 3 >= kept.length * 2) L = len;
  const endNote = opening[L - 1];
  const mark = L === n ? "=" : L < n ? `shorter by ${n - L}` : `longer by ${L - n}`;
  rows.push(`| ${name(p.id)} | ${n} (${st.subject[n - 1][2]} at ${where(st.subject[n - 1][0])}) | ${L} (${endNote.pitch} at ${where(endNote.on)}) | ${mark} | ${kept.length} | ${kept.map((x) => x.k).sort((a, b) => a - b).join(" ")} |`);
  if (L !== n) differ.push(name(p.id));
}
const out = [
  "# Where the subject ends by what Bach keeps (criterion (a), D163)",
  "",
  "Generated by `node tools/wtc/kept.ts`. For each fugue: the settled subject's length in notes; the longest opening",
  "that most of the later statements keep, note for note in their intervals (an octave's displacement and a tonal",
  "head allowed); how many statements were measured and how many notes each keeps (the opening line runs a dozen",
  "notes beyond the settled end, so a statement can keep more than the settled subject). Statements are those the",
  "analysis finds that keep at least half the settled subject; ornamented or rhythmically varied statements stop",
  "early and pull the length down, so a shorter result is a question for the reader, not a verdict.",
  "",
  "| fugue | settled: notes (last) | kept by most: notes (last) | | statements | notes kept |",
  "|---|---|---|---|---|---|",
  ...rows,
  "",
  `Different from the settled subject in ${differ.length} of ${rows.length}: ${differ.join(", ")}.`,
];
writeFileSync("docs/wtc/KEPT.md", out.join("\n") + "\n");
