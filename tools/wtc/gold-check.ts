// The analysis measured on the gold standard (KNOWLEDGE-PLAN A2): the entries the study's analysis finds
// (src/wtc/library.ts fugueOf: entries, later subjects, augmentations and diminutions) against the fugues
// read completely by hand (data/wtc/gold/*.json, PROTOCOL.md there); and the hand readings against
// Ledbetter's claims where he makes them (data/wtc/ledbetter-claims.txt), as a check on the readers.
// Writes docs/wtc/READING.md. Usage: node tools/wtc/gold-check.ts
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import type { WtcPiece } from "../../src/wtc/corpus.ts";
import { fugueOf } from "../../src/wtc/library.ts";
import { TPQ } from "../../src/wtc/fugue.ts";

interface GoldEntry {
  subject?: number;
  voice: number;
  bar: number;
  beat: number;
  form?: string;
  complete?: boolean | string;
  degree?: string;
}
interface GoldCadence {
  bar: number;
  beat: number;
  key: string;
  kind: string;
}
interface Gold {
  id: string;
  entries: GoldEntry[];
  cadences: GoldCadence[];
}

const pieces = [...(JSON.parse(readFileSync("data/wtc/fugues.json", "utf8")) as WtcPiece[]), ...(JSON.parse(readFileSync("data/wtc/more.json", "utf8")) as WtcPiece[])];
const dir = "data/wtc/gold";
const golds: Gold[] = readdirSync(dir).filter((f) => f.endsWith(".json")).map((f) => JSON.parse(readFileSync(`${dir}/${f}`, "utf8")));
const claims = readFileSync("data/wtc/ledbetter-claims.txt", "utf8").split("\n").filter((l) => /^wtc\d[fp]\d\d /.test(l));

const out: string[] = [
  "# How well the analysis reads Bach's fugues",
  "",
  "Generated by `node tools/wtc/gold-check.ts` (KNOWLEDGE-PLAN A2). The gold standard: fugues read completely by",
  "hand on one protocol (`data/wtc/gold/PROTOCOL.md`), independently of the analysis. An entry found by the analysis",
  "matches a hand-read entry in the same voice beginning within a beat of it (and, for fugues on several subjects,",
  "of the same subject). Precision: the share of the analysis's entries the readers confirm; recall: the share of",
  "the readers' entries the analysis finds.",
  "",
  "| fugue | hand-read entries | found | matched | precision | recall | missed: complete / altered / head | missed by form |",
  "|---|---|---|---|---|---|---|---|",
];
const detail: string[] = [];
let tm = 0;
let tg = 0;
let tf = 0;
for (const g of golds) {
  const p = pieces.find((x) => x.id === g.id)!;
  const lf = fugueOf(p);
  const [n, d] = p.meter.split("/").map(Number);
  const bar = (n * 4 * TPQ) / d;
  const beat = (4 * TPQ) / d;
  const first = p.bars.find((b) => b.n === 1)?.on ?? 0;
  const pad = (p.bars.find((b) => b.n === 1)?.on ?? 0) / TPQ > 1e-6 ? lf.barQuarters - first / TPQ : 0;
  // A found entry's onset in ticks of the encoding, then as the dump writes it.
  const ticks = (at: number) => Math.round((at - pad) * TPQ);
  const goldTicks = (e: GoldEntry) => first + (e.bar - 1) * bar + (e.beat - 1) * beat;
  const found = [
    ...lf.entries.map((e) => ({ e, subject: 1, kind: e.inverted ? "inverted" : "subject" })),
    ...lf.transformed.map((e) => ({ e, subject: 1, kind: (e.scale ?? 2) > 1 ? "augmented" : "diminished" })),
    ...lf.later.map((e) => ({ e, subject: e.subject ?? 2, kind: "subject" })),
  ].map((x) => ({ ...x, voice: lf.voice[x.e.notes[0]], on: ticks(x.e.at) }));
  const used = new Set<number>();
  const missed: GoldEntry[] = [];
  for (const ge of g.entries) {
    const k = found.findIndex((f, i) => !used.has(i) && f.voice === ge.voice && Math.abs(f.on - goldTicks(ge)) <= beat && (ge.subject ?? 1) === f.subject);
    if (k >= 0) used.add(k);
    else missed.push(ge);
  }
  const extra = found.filter((_, i) => !used.has(i));
  const matched = used.size;
  tm += matched;
  tg += g.entries.length;
  tf += found.length;
  const kind = (e: GoldEntry) => (e.complete === true || e.complete === undefined ? "complete" : String(e.complete).startsWith("head") ? "head" : "altered");
  const by = (k: string) => missed.filter((e) => kind(e) === k).length;
  const forms = new Map<string, number>();
  for (const e of missed) forms.set(e.form ?? "?", (forms.get(e.form ?? "?") ?? 0) + 1);
  const pct = (a: number, b: number) => (b ? `${Math.round((100 * a) / b)}%` : "–");
  out.push(`| ${g.id} | ${g.entries.length} | ${found.length} | ${matched} | ${pct(matched, found.length)} | ${pct(matched, g.entries.length)} | ${by("complete")} / ${by("altered")} / ${by("head")} | ${[...forms.entries()].map(([f, c]) => `${f} ${c}`).join(", ") || "–"} |`);
  const where = (t: number) => `${Math.floor((t - first) / bar) + 1}:${+(1 + ((t - first) % bar) / beat).toFixed(2)}`;
  detail.push(`### ${g.id}`, "");
  if (missed.length) detail.push(`Missed: ${missed.map((e) => `S${e.subject ?? 1} v${e.voice} ${e.bar}:${e.beat} ${e.form ?? ""}${kind(e) !== "complete" ? ` (${kind(e)})` : ""}`).join("; ")}.`, "");
  if (extra.length) detail.push(`Found, not in the reading: ${extra.map((f) => `S${f.subject} v${f.voice} ${where(f.on)} ${f.kind}`).join("; ")}.`, "");
  // The readers against Ledbetter.
  const mine = claims.filter((c) => c.startsWith(`${g.id.replace("wtc1f", "wtc1f").replace("wtc2f", "wtc2f")} entry`));
  if (mine.length) {
    const hit = mine.filter((c) => {
      const b = Number(/b\.(\d+)/.exec(c)?.[1]);
      return g.entries.some((e) => Math.abs(e.bar - b) <= 1);
    });
    detail.push(`The readers against Ledbetter's entry claims: ${hit.length} of ${mine.length}.${hit.length < mine.length ? ` Not in the reading: ${mine.filter((c) => !hit.includes(c)).map((c) => c.replace(/^\S+ /, "")).join("; ")}.` : ""}`, "");
  }
}
out.push(
  "",
  "**What it shows (12 October, eight fugues).** The entries the analysis finds are almost all real (precision",
  "98%); it misses about one in fourteen. The misses are of one kind above all: entries whose ending Bach",
  "changes, to cadence or to lead into what follows (II/13's later entries, I/11's last, BWV 903's answer at",
  "b. 41), and a few transformed entries in AoF VI. Fixed along the way: later subjects found a bar late (AoF IX's",
  "theme: recall 61% before, 94% after), and AoF VI's answers in diminution with a tonal head. The readers agree",
  "with 27 of Ledbetter's 28 entry claims in the four fugues of the 48; the 28th (II/17 b. 48) is, by the score check",
  "of his claim itself, the chromatic countersubject, not the subject.",
);
out.push("", `All: ${tg} entries read by hand, ${tf} found, ${tm} matched: precision ${Math.round((100 * tm) / Math.max(1, tf))}%, recall ${Math.round((100 * tm) / Math.max(1, tg))}%.`, "", "## By fugue", "", ...detail);
writeFileSync("docs/wtc/READING.md", out.join("\n") + "\n");
