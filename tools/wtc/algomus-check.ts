// The project's readings measured on the Algomus reference analysis of WTC I (data/wtc/algomus.json, built by
// tools/wtc/algomus.ts): the settled subjects' lengths, the entries the study's analysis finds, and the project's
// own hand readings (data/wtc/gold/) where the two overlap (I/11, I/12). Writes docs/wtc/ALGOMUS.md.
// Usage: node tools/wtc/algomus-check.ts
import { readFileSync, writeFileSync } from "node:fs";
import type { WtcPiece } from "../../src/wtc/corpus.ts";
import { fugueOf } from "../../src/wtc/library.ts";
import { TPQ } from "../../src/wtc/fugue.ts";
import type { AlgoFugue, AlgoOccurrence } from "./algomus.ts";

const pieces = JSON.parse(readFileSync("data/wtc/fugues.json", "utf8")) as WtcPiece[];
const algo = (JSON.parse(readFileSync("data/wtc/algomus.json", "utf8")) as { fugues: AlgoFugue[] }).fugues;
const settled = (JSON.parse(readFileSync("data/wtc/subjects-settled.json", "utf8")) as { fugues: Record<string, { voice: number; subject: [number, number, string][]; sure?: boolean; unsure?: unknown }> }).fugues;

const pct = (a: number, b: number) => (b ? `${Math.round((100 * a) / b)}%` : "–");
const name = (id: string) => `I/${Number(id.slice(5))}`;

/** The complete statements of a subject in the reference: subject, answer, inversion, augmentation, later subjects. */
const complete = (o: AlgoOccurrence) => /^(S|S-inv|Sinv|S-aug|S-var|S2|S3)$/.test(o.pattern);
const subjectNo = (o: AlgoOccurrence) => (o.pattern === "S2" ? 2 : o.pattern === "S3" ? 3 : 1);

const out: string[] = [
  "# The analysis measured on the Algomus reference analysis of WTC I",
  "",
  "Generated by `node tools/wtc/algomus-check.ts`. The reference: Giraud, Groult, Leguy and Levé, \"Computational Fugue",
  "Analysis\", *Computer Music Journal* 39/2 (2015), 77-96, and its data (http://www.algomus.fr/data; Open Database",
  "License 1.0), compiled from Prout (1910), Tovey (1924), Keller (1965), Bruhn (1993) and Charlier (2009) and the",
  "team's own analysis. It covers the 24 fugues of Book I only. Read into our units by `tools/wtc/algomus.ts`",
  "(`data/wtc/algomus.json`); its voices matched to ours by the notes (all 24 in the order of the file's letters).",
  "",
  "An entry matches when it is in the same voice and begins within a beat, as in `READING.md`.",
  "",
];

// 1. Subjects: where the subject ends.
out.push("## 1. Where the subject ends: the settled subjects against the reference", "");
out.push("| fugue | settled (quarters) | reference (quarters) | difference | the reference's alternatives |", "|---|---|---|---|---|");
let agree = 0;
const subjectRows: string[] = [];
for (const f of algo) {
  const s = settled[f.id];
  const first = f.occurrences.find((o) => o.pattern === "S");
  if (!s || !first) continue;
  const mine = (s.subject.at(-1)![0] + s.subject.at(-1)![1] - s.subject[0][0]) / TPQ;
  const theirs = first.len / TPQ;
  const diff = +(mine - theirs).toFixed(2);
  if (Math.abs(diff) <= 0.5) agree++;
  subjectRows.push(`| ${name(f.id)} | ${+mine.toFixed(2)} | ${+theirs.toFixed(2)} | ${diff === 0 ? "=" : diff > 0 ? `+${diff}` : diff} | ${f.alternatives.map((a) => a.replace(/^== S alternative\s*/, "")).join("; ") || ""} |`);
}
out.push(...subjectRows, "", `The settled subject's length within an eighth note of the reference's in ${agree} of ${subjectRows.length}. The reference measures a subject from its first note to where the next pattern takes over, in fractions of a bar, so a difference of an eighth or less is a difference of convention (whether the last note is counted whole), not of reading.`, "");

// 2. Entries: the study's analysis against the reference.
out.push("## 2. Entries: the study's analysis against the reference", "");
out.push("| fugue | reference: complete | found | matched | precision | recall | missed | found, not in the reference |", "|---|---|---|---|---|---|---|---|");
let tm = 0;
let tr = 0;
let tf = 0;
let incHit = 0;
let incAll = 0;
const disagreements: { id: string; side: string; voice: number; at: string; where: string }[] = [];
for (const f of algo) {
  const p = pieces.find((x) => x.id === f.id)!;
  const lf = fugueOf(p);
  const first = p.bars.find((b) => b.n === 1)?.on ?? 0;
  const pad = first / TPQ > 1e-6 ? lf.barQuarters - first / TPQ : 0;
  const ticks = (at: number) => Math.round((at - pad) * TPQ);
  const [n, d] = p.meter.split("/").map(Number);
  const bar = (n * 4 * TPQ) / d;
  const beat = (4 * TPQ) / d;
  const found = [
    ...lf.entries.map((e) => ({ e, subject: 1, kind: e.inverted ? "inverted" : "subject" })),
    ...lf.transformed.map((e) => ({ e, subject: 1, kind: (e.scale ?? 2) > 1 ? "augmented" : "diminished" })),
    ...lf.later.map((e) => ({ e, subject: e.subject ?? 2, kind: "subject" })),
  ].map((x) => ({ ...x, voice: lf.voice[x.e.notes[0]], on: ticks(x.e.at) }));
  const ref = f.occurrences.filter(complete);
  const inc = f.occurrences.filter((o) => /^S.*-?inc/.test(o.pattern));
  const used = new Set<number>();
  const missed: AlgoOccurrence[] = [];
  const near = (o: AlgoOccurrence, x: (typeof found)[0]) => (x.voice === o.voice || x.voice === o.voice2) && Math.abs(x.on - o.on) <= beat && x.subject === subjectNo(o);
  for (const o of ref) {
    const k = found.findIndex((x, i) => !used.has(i) && near(o, x));
    if (k >= 0) used.add(k);
    else missed.push(o);
  }
  // Heads the analysis counts as entries: matched to the reference's incomplete statements, not counted against it.
  const extra = found.filter((x, i) => !used.has(i));
  const extraInc = extra.filter((x) => inc.some((o) => (x.voice === o.voice || x.voice === o.voice2) && Math.abs(x.on - o.on) <= beat));
  incHit += extraInc.length;
  incAll += inc.length;
  const unexplained = extra.filter((x) => !extraInc.includes(x));
  tm += used.size;
  tr += ref.length;
  tf += found.length - extraInc.length;
  const where = (t: number) => `${Math.floor((t - first) / bar) + 1}:${+(1 + (((t - first) % bar) + bar) % bar / beat).toFixed(2)}`;
  const label = (o: AlgoOccurrence) => `${o.pattern} v${o.voice} b.${o.pos}${o.tags.length ? ` (${o.tags.join(", ")})` : ""}`;
  out.push(`| ${name(f.id)} | ${ref.length} | ${found.length - extraInc.length} | ${used.size} | ${pct(used.size, found.length - extraInc.length)} | ${pct(used.size, ref.length)} | ${missed.map(label).join("; ") || "–"} | ${unexplained.map((x) => `S${x.subject} v${x.voice} ${where(x.on)} ${x.kind}`).join("; ") || "–"} |`);
  disagreements.push(...missed.map((o) => ({ id: f.id, side: "reference only", voice: o.voice, at: label(o), where: where(o.on) })), ...unexplained.map((x) => ({ id: f.id, side: "analysis only", voice: x.voice, at: `S${x.subject} ${x.kind}`, where: where(x.on) })));
}
out.push(
  "",
  `All: ${tr} complete statements in the reference, ${tf} found by the analysis (heads the reference lists as incomplete statements left out of both counts), ${tm} matched: precision ${pct(tm, tf)}, recall ${pct(tm, tr)}. Of the reference's ${incAll} incomplete statements, the analysis reports ${incHit} as entries.`,
  "",
);

// 2b. Every disagreement judged from the notes (data/wtc/algomus-adjudicated.json).
const adj = (JSON.parse(readFileSync("data/wtc/algomus-adjudicated.json", "utf8")) as { items: { id: string; side: string; voice: number; at: string; where: string; verdict: string; detail: string }[] }).items;
const count = (side: string, v: string) => adj.filter((x) => x.side === side && x.verdict === v).length;
const ao = (v: string) => count("analysis only", v);
const ro = (v: string) => count("reference only", v);
// In I/4 the reference starts the second subject on its anacrusis, the analysis an eighth into the run: the same
// statements on both sides ("twins"), counted once, as found late.
const twin = (x: { id: string; side: string; at: string; verdict: string }) => x.id === "wtc1f04" && x.side === "analysis only" && x.at.startsWith("S2") && /complete|elsewhere/.test(x.verdict);
const twins = adj.filter(twin).length;
const realExtra = adj.filter((x) => x.side === "analysis only" && /complete|altered/.test(x.verdict) && !twin(x)).length;
const pick = (side: string, v: string, k = 4) => adj.filter((x) => x.side === side && x.verdict === v && !twin(x)).slice(0, k).map((x) => `${name(x.id)} v${x.voice} ${x.where}`).join(", ");
out.push(
  "### Each disagreement judged from the notes",
  "",
  `A reader judged all ${adj.length} disagreements from the notes, with neither analysis in view (\`data/wtc/algomus-adjudicated.json\`, with a reason for each).`,
  "",
  "| | complete | altered | head | begins elsewhere | none |",
  "|---|---|---|---|---|---|",
  `| found by the analysis only (${adj.filter((x) => x.side === "analysis only").length}) | ${ao("complete")} | ${ao("altered")} | ${ao("head")} | ${ao("elsewhere")} | ${ao("none")} |`,
  `| in the reference only (${adj.filter((x) => x.side === "reference only").length}) | ${ro("complete")} | ${ro("altered")} | ${ro("head")} | ${ro("elsewhere")} | ${ro("none")} |`,
  "",
  `- **The reference is reliable on what it lists** (${ro("complete") + ro("altered")} of its ${adj.filter((x) => x.side === "reference only").length} statements our analysis missed are real), **but not exhaustive**: ${realExtra} real statements found only by the analysis (besides I/4's second subject, below) (${pick("analysis only", "complete")}; altered: ${pick("analysis only", "altered")}): late statements compressed by a bar in I/15, inversions in I/15, a statement in C♯ minor in I/9, stretto partners in I/4.`,
  `- **The analysis's errors are over-detection:** ${ao("head")} heads, mostly figures in episodes (I/3 bb. 22-24 and 35-41, I/5's demisemiquaver run, I/15's coda), and ${ao("none")} false entries (cadential basses and free lines in I/4, countersubject ends in I/18, the chain of fourths in I/19's episodes). Some heads are real stretto entries the reference leaves out (I/8 bb. 52-54).`,
  `- **Its misses** are statements with a varied head or a changed ending (I/8's inversions, I/22 b. 48, I/23 b. 20, I/24 b. 47), and in I/4 the second subject begun an eighth too late: the reference, rightly, starts it on its three-crotchet anacrusis (${twins} statements on each side, the same ones).`,
  `- **Measured on the notes** (the reference corrected by the reader: its ${tr} statements less ${ro("head")} head, plus the ${realExtra} it omits): precision ${pct(tm + realExtra, tf)} (${pct(tm + realExtra + twins, tf)} counting I/4's late-begun second subject as found); ${pct(ao("head"), tf)} of what the analysis reports is a head, ${pct(ao("none"), tf)} no statement at all; recall ${pct(tm + realExtra, tr - ro("head") + realExtra)} (${pct(tm + realExtra + twins, tr - ro("head") + realExtra)}).`,
  "",
);

// 3. The project's hand readings against the reference, where both exist.
out.push("## 3. The project's hand readings (the gold standard) against the reference", "");
for (const id of ["wtc1f11", "wtc1f12"]) {
  const g = JSON.parse(readFileSync(`data/wtc/gold/${id}.json`, "utf8")) as { entries: { voice: number; bar: number; beat: number; form?: string; complete?: boolean | string; subject?: number }[]; cadences: { bar: number; beat: number; key: string; kind: string }[] };
  const f = algo.find((x) => x.id === id)!;
  const p = pieces.find((x) => x.id === id)!;
  const [n, d] = p.meter.split("/").map(Number);
  const bar = (n * 4 * TPQ) / d;
  const beat = (4 * TPQ) / d;
  const first = p.bars.find((b) => b.n === 1)?.on ?? 0;
  const gt = (e: { bar: number; beat: number }) => first + (e.bar - 1) * bar + (e.beat - 1) * beat;
  const ref = f.occurrences.filter(complete);
  // Our statements other than heads (complete or altered: the reference counts altered statements, "varied").
  const both = g.entries.filter((e) => !String(e.complete ?? "").startsWith("head"));
  const hit = ref.filter((o) => both.some((e) => (e.voice === o.voice || e.voice === o.voice2) && Math.abs(gt(e) - o.on) <= beat));
  const refOnly = ref.filter((o) => !hit.includes(o));
  const goldOnly = both.filter((e) => !ref.some((o) => (e.voice === o.voice || e.voice === o.voice2) && Math.abs(gt(e) - o.on) <= beat));
  const whereG = (e: { voice: number; bar: number; beat: number; form?: string }) => `v${e.voice} ${e.bar}:${e.beat} ${e.form ?? ""}`;
  out.push(`### ${name(id)}`, "");
  out.push(`- **Entries.** Statements (complete or altered): the reference ${ref.length}, our readers ${both.length}, in common ${hit.length}.${refOnly.length ? ` Only in the reference: ${refOnly.map((o) => `${o.pattern} v${o.voice} b.${o.pos}${o.tags.length ? ` (${o.tags.join(", ")})` : ""}`).join("; ")}.` : ""}${goldOnly.length ? ` Only in our reading: ${goldOnly.map(whereG).join("; ")}.` : ""}`);
  // Cadences: the reference lists only conclusive ones (PAC, root-position IAC, strong HC and DC).
  const cHit = f.cadences.filter((c) => g.cadences.some((x) => Math.abs(gt(x) - c.on) <= bar));
  out.push(
    `- **Cadences.** The reference lists ${f.cadences.length} (only conclusive ones: PAC, root-position IAC, the strong HC or DC before a coda): ${f.cadences.map((c) => `b.${c.pos} ${c.degree} ${c.kind}`).join("; ")}. Our readers list ${g.cadences.length}, every phrase close; ${cHit.length} of the reference's ${f.cadences.length} are among them (within a bar).`,
    "",
  );
}

// 4. What the reference has that the project does not yet read.
const cs = algo.map((f) => ({ id: f.id, n: new Set(f.occurrences.filter((o) => /^CS/.test(o.pattern)).map((o) => o.pattern.replace(/-inc$/, ""))).size, occ: f.occurrences.filter((o) => /^CS/.test(o.pattern)).length }));
out.push(
  "## 4. Held for later steps",
  "",
  `- **Countersubjects (A5).** The reference names countersubjects in ${cs.filter((x) => x.n).length} of 24 fugues (${cs.reduce((a, x) => a + x.occ, 0)} occurrences; two or more in ${cs.filter((x) => x.n >= 2).length}): ${cs.filter((x) => x.n).map((x) => `${name(x.id)} ${x.n}`).join(", ")}. The test for A5.`,
  `- **Cadences (ANALYSIS CORE).** ${algo.reduce((a, f) => a + f.cadences.length, 0)} conclusive cadences with key and kind over the 24 fugues: a test set for the cadence finder, beside our gold standard's 109 phrase closes. The two count different things (the reference only the conclusive ones), and the finder is to be measured on each separately.`,
  `- **Pedal points.** ${algo.reduce((a, f) => a + f.pedals.length, 0)} pedals with degree and length.`,
  "",
  "## 5. What follows (12 October)",
  "",
  "- **I/11's subject, for the owner (KNOWLEDGE-PLAN E1).** The settled subject runs to C4 at 5:1, the rising sixteenths",
  "  included; the reference ends it three bars after the upbeat (Keller an eighth later). The reader finds that the",
  "  statements at bb. 27, 38 and 46 keep the subject through the reference's ending and leave the sixteenths (at 31:1,",
  "  42:1, 50:1): what Bach keeps when he restates it argues for the shorter subject. Our gold reading called those three",
  "  heads because it measured them against the longer one.",
  "- **The entries analysis (fixes to weigh):** heads in episodes reported as entries (I/3, I/5: a head restarted in",
  "  sequence is not an entry); statements with a varied head missed (I/8, I/22-24); I/4's second subject to begin on",
  "  its anacrusis (data/wtc/later-subjects.json).",
  "- **Book II has no such reference.** Prout (1910) and Sampson (1900), both open on the Internet Archive, analyse all 48",
  "  and could be typed in as a second opinion for Book II.",
  "",
);
if (process.argv[2]) writeFileSync(process.argv[2], JSON.stringify(disagreements, null, 1));
writeFileSync("docs/wtc/ALGOMUS.md", out.join("\n") + "\n");
console.log(out.filter((l) => /^All:|^The settled|^- \*\*/.test(l)).join("\n"));
