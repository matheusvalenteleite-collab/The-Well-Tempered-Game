// Bach's other fugues (D160): the Art of Fugue (Contrapuncti I-X) and BWV 903's fugue from the Mutopia
// editions (read by tools/wtc/import_more.py into data/wtc/more-ly.json), the Musical Offering's two
// ricercars from Sapp's Humdrum encoding; written as pieces of the corpus (corpus.ts) to
// data/wtc/more.json, with an import check in docs/wtc/IMPORT-MORE.md.
// Usage: python3 tools/wtc/import_more.py && node tools/wtc/import-more.ts
import { readFileSync, writeFileSync } from "node:fs";
import { parseKern, TPQ } from "../../src/wtc/kern.ts";
import type { WtcNote, WtcPiece } from "../../src/wtc/corpus.ts";

export const TITLES: Record<string, { title: string; bwv: string }> = {
  aof01: { title: "Art of Fugue, Contrapunctus I", bwv: "1080/1" },
  aof02: { title: "Art of Fugue, Contrapunctus II", bwv: "1080/2" },
  aof03: { title: "Art of Fugue, Contrapunctus III", bwv: "1080/3" },
  aof04: { title: "Art of Fugue, Contrapunctus IV", bwv: "1080/4" },
  aof05: { title: "Art of Fugue, Contrapunctus V", bwv: "1080/5" },
  aof06: { title: "Art of Fugue, Contrapunctus VI (in stylo francese)", bwv: "1080/6" },
  aof07: { title: "Art of Fugue, Contrapunctus VII (per augmentationem et diminutionem)", bwv: "1080/7" },
  aof08: { title: "Art of Fugue, Contrapunctus VIII (a 3)", bwv: "1080/8" },
  aof09: { title: "Art of Fugue, Contrapunctus IX (alla duodecima)", bwv: "1080/9" },
  aof10: { title: "Art of Fugue, Contrapunctus X (alla decima)", bwv: "1080/10" },
  mo3: { title: "Musical Offering, Ricercar a 3", bwv: "1079/1" },
  mo6: { title: "Musical Offering, Ricercar a 6", bwv: "1079/5" },
  bwv903f: { title: "Chromatic Fantasia and Fugue, the fugue", bwv: "903" },
};

const q = (x: number) => Math.round(x * TPQ);
const pieces: WtcPiece[] = [];
const ly = JSON.parse(readFileSync("data/wtc/more-ly.json", "utf8")) as Record<string, { key: string; meter: string; length: number; partial: number; bars: { n: number; on: number }[]; voices: [number, number, string, number][][] }>;
let number = 0;
for (const [id, p] of Object.entries(ly)) {
  pieces.push({
    id,
    book: 0,
    number: ++number,
    kind: "fugue",
    key: p.key.toUpperCase(),
    mode: p.key === p.key.toLowerCase() ? "minor" : "major",
    bwv: TITLES[id].bwv,
    meter: p.meter,
    voices: p.voices.map((v) => v.map(([on, dur, pitch, sub]) => [q(on), q(dur), pitch, sub] as WtcNote)),
    bars: p.bars.map((b) => ({ n: b.n, on: q(b.on) })),
    length: q(p.length),
  });
}
for (const [id, file] of [["mo3", "offering-001.krn"], ["mo6", "offering-002.krn"]]) {
  const k = parseKern(readFileSync(`data/sources/bach-fugues-more/kern/${file}`, "utf8"));
  pieces.push({
    id,
    book: 0,
    number: ++number,
    kind: "fugue",
    key: "C",
    mode: "minor",
    bwv: TITLES[id].bwv,
    meter: k.meter ?? "4/4",
    voices: k.voices.map((v) => v.map((n) => [n.on, n.dur, n.pitch, n.sub] as WtcNote)),
    bars: k.bars,
    length: k.length,
  });
}
const report = ["# Bach's other fugues: import check", "", "Generated by `node tools/wtc/import-more.ts` (sources: data/sources/bach-fugues-more/SOURCE.md).", "", "| piece | metre | voices | notes per voice | bars | voice ends |", "|---|---|---|---|---|---|"];
for (const p of pieces) {
  const [n, d] = p.meter.split("/").map(Number);
  const bar = (n * 4 * TPQ) / d;
  const early = p.voices.filter((v) => v.length && v[v.length - 1][0] + v[v.length - 1][1] < p.length - bar).length;
  report.push(`| ${TITLES[p.id].title} | ${p.meter} | ${p.voices.length} | ${p.voices.map((v) => v.filter((x) => x[3] === 0).length).join(", ")} | ${Math.round(p.length / bar)} | ${early ? `${early} early` : "ok"} |`);
}
writeFileSync("data/wtc/more.json", JSON.stringify(pieces));
writeFileSync("docs/wtc/IMPORT-MORE.md", report.join("\n") + "\n");
console.log(report.join("\n"));
