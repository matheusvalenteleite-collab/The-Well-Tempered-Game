// The settled subjects (docs/wtc/SUBJECTS.md, D160): the readers' decisions (data/wtc/subject-readings/*.json,
// one protocol, PROTOCOL.md there) turned into notes from the encodings: for each fugue the voice and onset of
// the first entry, the subject's notes, the answer's kind and mutated notes, the confidence and the reason.
// Writes data/wtc/subjects-settled.json. Usage: node tools/wtc/settle-subjects.ts
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import type { WtcPiece } from "../../src/wtc/corpus.ts";
import { entryOrder, line } from "../../src/wtc/fugue.ts";

interface Reading {
  id: string;
  subject_end: number;
  subject_end_at: string;
  subject_last_pitch: string;
  answer: string;
  answer_end: number;
  mutated: number[];
  codetta_before_answer_beats: number | null;
  codetta_before_third_beats: number | null;
  confidence: "sure" | "unsure";
  reason: string;
  note?: string;
}
const pieces = [...(JSON.parse(readFileSync("data/wtc/fugues.json", "utf8")) as WtcPiece[]), ...(JSON.parse(readFileSync("data/wtc/more.json", "utf8")) as WtcPiece[])];
const dir = "data/wtc/subject-readings";
const readings: Reading[] = readdirSync(dir).filter((f) => f.endsWith(".json")).flatMap((f) => JSON.parse(readFileSync(`${dir}/${f}`, "utf8"))).filter((r) => r && typeof r.id === "string" && "subject_end" in r);
const out: Record<string, unknown> = {};
for (const r of readings) {
  const p = pieces.find((x) => x.id === r.id);
  if (!p) throw new Error(`no piece ${r.id}`);
  const order = entryOrder(p);
  const [v1, on1] = order[0];
  const [v2, on2] = order[1];
  const l1 = line(p.voices[v1]).filter((n) => n.on >= on1);
  const subject = l1.slice(0, r.subject_end + 1);
  if (subject[subject.length - 1].pitch !== r.subject_last_pitch) throw new Error(`${r.id}: index ${r.subject_end} is ${subject[subject.length - 1].pitch}, the reading says ${r.subject_last_pitch}`);
  const l2 = line(p.voices[v2]).filter((n) => n.on >= on2);
  out[r.id] = {
    voice: v1,
    subject: subject.map((n) => [n.on, n.dur, n.pitch]),
    answerVoice: v2,
    answer: l2.slice(0, r.answer_end + 1).map((n) => [n.on, n.dur, n.pitch]),
    answerKind: r.answer,
    mutated: r.mutated,
    codettaBeforeAnswer: r.codetta_before_answer_beats,
    codettaBeforeThird: r.codetta_before_third_beats,
    confidence: r.confidence,
    reason: r.reason,
    note: r.note ?? "",
  };
}
writeFileSync("data/wtc/subjects-settled.json", JSON.stringify({ about: "Subjects settled by hand from the score (D160; tools/wtc/settle-subjects.ts). Times in ticks (1920 a quarter).", fugues: out }, null, 0));
console.log(Object.keys(out).length, "settled");

// The document: every subject, its notes, the answer, the reader's reason (docs/wtc/SUBJECTS.md).
const TITLE: Record<string, string> = {
  aof01: "AoF I", aof02: "AoF II", aof03: "AoF III", aof04: "AoF IV", aof05: "AoF V", aof06: "AoF VI", aof07: "AoF VII", aof08: "AoF VIII", aof09: "AoF IX", aof10: "AoF X", aof11: "AoF XI", aof14: "AoF XIV", mo3: "MO ricercar a 3", mo6: "MO ricercar a 6", bwv903f: "BWV 903 fugue",
};
const nameOf = (id: string) => TITLE[id] ?? `${id[3] === "1" ? "I" : "II"}/${Number(id.slice(5))}`;
const pc = (p: string) => p.replace(/-?\d+$/, "").replace("##", "𝄪").replace("#", "♯").replace("bb", "𝄫").replace(/(?<=.)b/, "♭");
const doc: string[] = [
  "# The subjects of Bach's fugues, settled from the score",
  "",
  "Generated by `node tools/wtc/settle-subjects.ts` from the readers' decisions in `data/wtc/subject-readings/`",
  "(one protocol, `PROTOCOL.md` there; D160). Each subject's end was decided by reading the opening of the",
  "fugue: the subject is what the answer imitates, ending on a cadential arrival at or just before the",
  "answer's entry. Corrections made on review are marked in the reason. 'unsure' marks a defensible",
  "alternative end, named in the reason. The study screen uses these subjects (src/wtc/settled.ts); with",
  "them its entries agree with Ledbetter's claims as before (157 of 173) and one more stretto (40 of 47).",
  "",
  "| fugue | notes | subject | answer | mutated | confidence |",
  "|---|---|---|---|---|---|",
];
const order = (id: string) => (id.startsWith("wtc") ? id : `z${id}`);
for (const id of Object.keys(out).sort((a, b) => order(a).localeCompare(order(b)))) {
  const s = out[id] as { subject: [number, number, string][]; answerKind: string; mutated: number[]; confidence: string };
  doc.push(`| ${nameOf(id)} | ${s.subject.length} | ${s.subject.map((n) => pc(n[2])).join(" ")} | ${s.answerKind} | ${s.mutated.join(", ") || "–"} | ${s.confidence} |`);
}
doc.push("", "## Reasons", "");
for (const id of Object.keys(out).sort((a, b) => order(a).localeCompare(order(b)))) {
  const s = out[id] as { reason: string; note: string };
  doc.push(`- **${nameOf(id)}**: ${s.reason}${s.note ? ` *${s.note}*` : ""}`);
}
writeFileSync("docs/wtc/SUBJECTS.md", doc.join("\n") + "\n");
