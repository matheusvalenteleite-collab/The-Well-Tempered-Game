// D366: the Well-Tempered Clavier and the Inventions and Sinfonias, imported from licence-clean
// editions (tools/wtc/sources.ts; data/sources/{wtc-uct,wtc-openwtc,wtc-musescore}/SOURCE.md and
// data/wtc/sources/mutopia, data/sources/bach-inventions/mutopia) → data/wtc/{fugues,preludes,inventions}.json
// and data/wtc/ornaments.json (tools/wtc/ornaments.ts's tables added), with a validation report
// (docs/wtc/IMPORT.md: voices, notes, bars, the bar check, the voices' ends, each correction made).
// Usage: node tools/wtc/import.ts   (needs python3 for the LilyPond reader)
import { mkdirSync, writeFileSync } from "node:fs";
import { TPQ, type WtcPiece } from "../../src/wtc/corpus.ts";
import { readFugue, readInvention, readPrelude, ROOT, type OrnRow, type Read } from "./sources.ts";
import { ADDED, CONTRAPUNCTUS } from "./ornaments.ts";

const fugues: WtcPiece[] = [];
const preludes: WtcPiece[] = [];
const inventions: WtcPiece[] = [];
const ornaments: Record<string, OrnRow[]> = {};
const corrections: string[] = [];
const report: string[] = [
  "# The Well-Tempered Clavier: import check",
  "",
  "Generated by `node tools/wtc/import.ts` (D366) from the licence-clean editions (docs/wtc/SOURCES.md). For each",
  "piece: its source, voices, notes, bars; **bar check**: bars whose length (bar line to bar line) is not the",
  "meter's (the first, a pickup, and the last are allowed to differ); **voice ends**: voices whose",
  "last note ends more than a bar before the piece's end.",
  "",
  "| piece | source | key | voices | notes | bars | bar check | voice ends |",
  "|---|---|---|---|---|---|---|---|",
];
let problems = 0;
const take = (r: Read, into: WtcPiece[]) => {
  const p = r.piece;
  into.push(p);
  // The ornaments, sorted as before (voice, onset); II/1's signs the Bach-Gesellschaft prints and the edition leaves out (D206).
  const rows = [...r.orn];
  for (const [bar, pitch, signs, beat] of ADDED[p.id] ?? []) {
    const start = p.bars.find((b) => b.n === bar)!.on;
    const end = p.bars.find((b) => b.n === bar + 1)?.on ?? p.length;
    const hits: [number, number][] = [];
    p.voices.forEach((v, vi) => v.forEach((n) => n[2] === pitch && n[0] >= start && n[0] < end && (beat === undefined || n[0] === start + beat * TPQ) && hits.push([vi, n[0]])));
    if (hits.length !== 1) throw new Error(`${p.id} bar ${bar} ${pitch}: ${hits.length} notes`);
    const row = rows.find((x) => x[0] === hits[0][0] && x[1] === hits[0][1]);
    if (row) {
      if (!row[3].includes(signs)) row[3] += signs;
    } else rows.push([hits[0][0], hits[0][1], pitch, signs]);
  }
  rows.sort((a, b) => a[0] - b[0] || a[1] - b[1]);
  if (rows.length) ornaments[p.id] = rows;
  for (const c of r.notes) corrections.push(`| ${p.id} | ${c.replace(/\|/g, "/")} |`);
  const [num, den] = p.meter.split("/").map(Number);
  const barLen = (num * 4 * TPQ) / den;
  const odd = p.bars.slice(1, -1).filter((b, i, a) => i + 1 < a.length && a[i + 1].on - b.on !== barLen && b.n !== a[i + 1].n);
  const ends = p.voices.filter((v) => v.length && v[v.length - 1][0] + v[v.length - 1][1] < p.length - barLen).length;
  if (odd.length || ends) problems++;
  report.push(
    `| ${p.id} | ${r.source.replace(/^data\/(sources|wtc\/sources)\//, "")} | ${p.key} | ${p.voices.length} | ${p.voices.reduce((a, v) => a + v.length, 0)} | ${p.bars.length} | ${odd.length ? `${odd.length} odd (bar ${odd.slice(0, 3).map((b) => b.n).join(", ")})` : "ok"} | ${ends ? `${ends} early` : "ok"} |`,
  );
};
for (const book of [1, 2] as const)
  for (let n = 1; n <= 24; n++) {
    take(readPrelude(book, n), preludes);
    take(readFugue(book, n), fugues);
  }
for (const kind of ["invention", "sinfonia"] as const) for (let n = 1; n <= 15; n++) take(readInvention(kind, n), inventions);
ornaments["bwv1080-14"] = CONTRAPUNCTUS.map((r) => [...r] as OrnRow);

report.splice(8, 0, `${fugues.length} fugues, ${preludes.length} preludes, ${inventions.length} inventions and sinfonias; ${problems} pieces with something to look at.`, "");
report.push("", "## Corrections", "", "Each correction to an edition as read (tools/wtc/corrections.ts), and what the reader did beside the text (repeats, written-out trills).", "", "| piece | correction |", "|---|---|", ...corrections);
mkdirSync(`${ROOT}data/wtc`, { recursive: true });
writeFileSync(`${ROOT}data/wtc/fugues.json`, JSON.stringify(fugues));
writeFileSync(`${ROOT}data/wtc/preludes.json`, JSON.stringify(preludes));
writeFileSync(`${ROOT}data/wtc/inventions.json`, JSON.stringify(inventions));
writeFileSync(`${ROOT}data/wtc/ornaments.json`, JSON.stringify(ornaments) + "\n");
writeFileSync(`${ROOT}docs/wtc/IMPORT.md`, report.join("\n") + "\n");
const counts: Record<string, number> = {};
for (const rows of Object.values(ornaments)) for (const r of rows) for (const c of r[3] || "·") counts[c] = (counts[c] ?? 0) + 1;
console.log(report.slice(8, 9).join("\n"));
console.log(`problems: ${problems}; corrections ${corrections.length}; ornaments: ${Object.keys(ornaments).length} pieces`, counts);
