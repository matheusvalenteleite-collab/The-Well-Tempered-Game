// The project's readings measured on Groocock's analyses of the 48 (J. Groocock, Fugal Composition: A Guide to the
// Study of Bach's '48', ed. Y. Tomita, Greenwood 2003; data/wtc/groocock/, his tables as data, see SOURCE.md there),
// beside the Algomus reference for Book I (data/wtc/algomus.json). Groocock gives entries by bars only ("19-22"), so
// entries are matched by voice and first bar (within a bar). Writes docs/wtc/GROOCOCK.md.
// Usage: node tools/wtc/groocock-check.ts [data dir]
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import type { WtcPiece } from "../../src/wtc/corpus.ts";
import { fugueOf } from "../../src/wtc/library.ts";
import { TPQ } from "../../src/wtc/fugue.ts";
import type { AlgoFugue } from "./algomus.ts";

interface GEntry {
  bars: string | null;
  voice: string | null;
  form: string | null;
  key: string | null;
  section?: string | null;
  stretto?: string | null;
  notes?: string | null;
  subject_no?: number;
}
interface GFugue {
  id: string;
  entries: GEntry[];
  groocock?: { group?: number; pages?: string };
}

const dir = process.argv[2] ?? "data/wtc/groocock";
const pieces = JSON.parse(readFileSync("data/wtc/fugues.json", "utf8")) as WtcPiece[];
const algo = (JSON.parse(readFileSync("data/wtc/algomus.json", "utf8")) as { fugues: AlgoFugue[] }).fugues;
const files = readdirSync(dir).filter((f) => /^wtc[12]f\d\d\.json$/.test(f));
const gs = files.map((f) => JSON.parse(readFileSync(`${dir}/${f}`, "utf8")) as GFugue);
const name = (id: string) => `${id[3] === "1" ? "I" : "II"}/${Number(id.slice(5))}`;
const pct = (a: number, b: number) => (b ? `${Math.round((100 * a) / b)}%` : "–");

/** Groocock's voice names to our voices (0 = top), by the number of voices. */
function voiceOf(v: string | null, count: number): number | null {
  if (!v) return null;
  const s = v.trim().toLowerCase();
  const names: Record<number, Record<string, number>> = {
    2: { soprano: 0, upper: 0, alto: 1, bass: 1, lower: 1 },
    3: { soprano: 0, middle: 1, alto: 1, tenor: 1, bass: 2 },
    4: { soprano: 0, alto: 1, tenor: 2, "first tenor": 2, bass: 3 },
    5: { "soprano 1": 0, "soprano 2": 1, alto: 2, tenor: 3, bass: 4 },
  };
  return names[count]?.[s] ?? null;
}
const firstBar = (b: string | null) => (b && /^\d+/.test(b) ? Number(/^(\d+)/.exec(b)![1]) : null);

const out: string[] = [
  "# The analysis measured on Groocock's readings of the 48",
  "",
  "Generated by `node tools/wtc/groocock-check.ts`. The reference: Joseph Groocock, *Fugal Composition: A Guide to the",
  "Study of Bach's '48'*, ed. Yo Tomita (Westport: Greenwood, 2003), his table of each fugue's entries turned into data",
  "(`data/wtc/groocock/`). He gives entries by bars, not beats, so an entry matches one in the same voice beginning",
  "within a bar. Entries given in more than one voice at once, or in a voice that cannot be told, are left out.",
  "Book I can be set beside the Algomus reference (`ALGOMUS.md`), Book II only beside Groocock.",
  "",
  "| fugue | group | Groocock's entries | found | matched | precision | recall | Groocock and Algomus agree |",
  "|---|---|---|---|---|---|---|---|",
];
const sets: Record<string, { g: number; f: number; m: number }> = { I: { g: 0, f: 0, m: 0 }, II: { g: 0, f: 0, m: 0 } };
let ga = 0;
let gaAll = 0;
const detail: string[] = [];
for (const g of gs.sort((a, b) => a.id.localeCompare(b.id))) {
  const p = pieces.find((x) => x.id === g.id);
  if (!p) continue;
  const lf = fugueOf(p);
  const count = p.voices.length;
  const first = p.bars.find((b) => b.n === 1)?.on ?? 0;
  const pad = first / TPQ > 1e-6 ? lf.barQuarters - first / TPQ : 0;
  const [n, d] = p.meter.split("/").map(Number);
  const bar = (n * 4 * TPQ) / d;
  const barOf = (ticks: number) => Math.floor((ticks - first) / bar) + 1;
  const found = [...lf.entries, ...lf.transformed, ...lf.later].map((e) => ({ voice: lf.voice[e.notes[0]], bar: barOf(Math.round((e.at - pad) * TPQ)) }));
  const theirs = g.entries.map((e) => ({ e, voice: voiceOf(e.voice, count), bar: firstBar(e.bars) })).filter((x) => x.voice !== null && x.bar !== null) as { e: GEntry; voice: number; bar: number }[];
  const used = new Set<number>();
  const missed: typeof theirs = [];
  for (const t of theirs) {
    const k = found.findIndex((f, i) => !used.has(i) && f.voice === t.voice && Math.abs(f.bar - t.bar) <= 1);
    if (k >= 0) used.add(k);
    else missed.push(t);
  }
  const book = g.id[3] === "1" ? "I" : "II";
  sets[book].g += theirs.length;
  sets[book].f += found.length;
  sets[book].m += used.size;
  // Two authorities, Book I: Groocock's entries against Algomus's statements (complete and incomplete).
  let agree = "–";
  const a = algo.find((x) => x.id === g.id);
  if (a) {
    const aBars = a.occurrences.filter((o) => /^S/.test(o.pattern)).map((o) => ({ voice: o.voice, bar: barOf(o.on) }));
    const hit = theirs.filter((t) => aBars.some((x) => x.voice === t.voice && Math.abs(x.bar - t.bar) <= 1)).length;
    ga += hit;
    gaAll += theirs.length;
    agree = `${hit} of ${theirs.length} (Algomus ${aBars.length})`;
  }
  out.push(`| ${name(g.id)} | ${g.groocock?.group ?? ""} | ${theirs.length} | ${found.length} | ${used.size} | ${pct(used.size, found.length)} | ${pct(used.size, theirs.length)} | ${agree} |`);
  const extra = found.filter((_, i) => !used.has(i));
  if (missed.length || extra.length)
    detail.push(
      `- **${name(g.id)}.**${missed.length ? ` Groocock's entries not found: ${missed.map((t) => `${t.e.voice} b. ${t.e.bars} (${t.e.form ?? ""}${t.e.notes ? `; ${t.e.notes.slice(0, 60)}` : ""})`).join("; ")}.` : ""}${extra.length ? ` Found, not in Groocock: ${extra.map((f) => `v${f.voice} b. ${f.bar}`).join(", ")}.` : ""}`,
    );
}
out.push("");
for (const [b, s] of Object.entries(sets)) out.push(`- **Book ${b}:** Groocock ${s.g} entries, the analysis ${s.f}, matched ${s.m}: precision ${pct(s.m, s.f)}, recall ${pct(s.m, s.g)}.`);
out.push(`- **Groocock against Algomus (Book I):** ${ga} of Groocock's ${gaAll} entries are in the Algomus reference (${pct(ga, gaAll)}).`, "");
out.push("Precision here is a lower bound: Groocock lists the entries that matter to his account of the form, and an entry the analysis finds that he does not list is not thereby false (`ALGOMUS.md` judged such cases from the notes).", "");
out.push("## The differences, fugue by fugue", "", ...detail, "");
writeFileSync("docs/wtc/GROOCOCK.md", out.join("\n") + "\n");
console.log(out.filter((l) => l.startsWith("- **Book") || l.startsWith("- **Groocock against")).join("\n"));
