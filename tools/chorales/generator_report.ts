/**
 * How good is the chorale generator (src/chorale/generate/, Phase A steps 1-2)? Every measure is
 * taken on melodies the models have not seen: Bach's chorales with every setting of the tune held
 * out, Kittel's melodies with Bach's settings of them held out (Kittel's basses are never trained on).
 *
 * Output: docs/chorales/GENERATOR.md.   Run:  node tools/chorales/generator_report.ts
 */
import { writeFileSync } from "node:fs";
import { BACH, KITTEL, kittelBasses, kittelMelody, melodyOf, type BachChorale, type KittelChorale } from "../../src/chorale/generate/corpus.ts";
import { bestHarmony, bestSetting, diverseSettings, fixedFromPlan, phraseEnds, trainModels, type Models, type Setting } from "../../src/chorale/generate/index.ts";
import { draw } from "../../src/chorale/generate/model.ts";
import { rng } from "../../src/counterpoint/choices/cantus.ts";

const pct = (a: number, b: number) => `${b ? Math.round((100 * a) / b) : 0}%`;
const out: string[] = [];
const say = (s = "") => {
  out.push(s);
  console.log(s);
};

// ---- Bach, each tune held out ----
const tunes = [...new Set(BACH.map((c) => c.tune))];
let planHit = 0,
  planN = 0;
const harm = { own: 0, best: 0, free: 0, n: 0 };
for (const t of tunes) {
  const models = trainModels(BACH.filter((c) => c.tune !== t));
  for (const c of BACH.filter((c) => c.tune === t)) {
    const m = melodyOf(c);
    const ends = phraseEnds(m);
    const bachPlan = ends.map((e) => c.notes[e.index].chord);
    const best = models.plan.best(m);
    best.forEach((ch, k) => ((planHit += ch === bachPlan[k] ? 1 : 0), planN++));
    const own = bestHarmony(models.harmony, m, fixedFromPlan(m, ends, bachPlan));
    const withBest = bestHarmony(models.harmony, m, fixedFromPlan(m, ends, best));
    const free = bestHarmony(models.harmony, m, m.notes.map(() => null));
    c.notes.forEach((n, i) => {
      harm.own += own[i] === n.chord ? 1 : 0;
      harm.best += withBest[i] === n.chord ? 1 : 0;
      harm.free += free[i] === n.chord ? 1 : 0;
      harm.n++;
    });
  }
}

// Benchmark: two of Bach's settings of one tune with the same melody degrees, note by note.
let twinSame = 0,
  twinN = 0,
  twinPairs = 0;
for (const t of tunes) {
  const cs = BACH.filter((c) => c.tune === t);
  for (let a = 0; a < cs.length; a++)
    for (let b = a + 1; b < cs.length; b++) {
      const x = cs[a].notes,
        y = cs[b].notes;
      if (x.length !== y.length || x.some((n, i) => n.deg !== y[i].deg)) continue;
      twinPairs++;
      x.forEach((n, i) => ((twinSame += n.chord === y[i].chord ? 1 : 0), twinN++));
    }
}

say("# The chorale generator: steps 1-2 (cadence plan, chords)");
say();
say("Generated by `node tools/chorales/generator_report.ts`. Code: `src/chorale/generate/`; training data:");
say("`data/chorales/generator/bach-events.json` (`tools/chorales/generator_data.py`). Chords are Kirnberger's");
say("fundamentals as degrees of the chorale's key, one under every on-beat melody note, as at level 2.");
say("Every number is measured on melodies the models have not seen.");
say();
say("## 1. Bach's chorales, every setting of the tune held out");
say();
say(`${BACH.length} chorales, ${tunes.length} tunes, ${planN} phrase ends, ${harm.n} melody notes.`);
say();
say("| what the generator is given | its most likely choice is Bach's |");
say("|---|---|");
say(`| the melody: the cadence chord at each phrase end (step 1) | ${pct(planHit, planN)} of phrase ends |`);
say(`| the melody: the chords, with no plan | ${pct(harm.free, harm.n)} of notes |`);
say(`| the melody and its own best plan (steps 1 and 2) | ${pct(harm.best, harm.n)} of notes |`);
say(`| the melody and Bach's own cadence plan (step 2 alone) | ${pct(harm.own, harm.n)} of notes |`);
say(`| *benchmark:* two of Bach's settings of one tune (${twinPairs} pairs with the same melody degrees) | ${pct(twinSame, twinN)} of notes |`);
say();

// ---- Kittel's 24 melodies ----
interface KStats {
  attested: number;
  n: number;
  cover: number;
  coverN: number;
  spread: number;
  spreadN: number;
  cadAttested: number;
  cadN: number;
  plans: number;
  bachSame: number;
  bachN: number;
}
const zero = (): KStats => ({ attested: 0, n: 0, cover: 0, coverN: 0, spread: 0, spreadN: 0, cadAttested: 0, cadN: 0, plans: 0, bachSame: 0, bachN: 0 });

/** Measure a set of settings (chords per note) of a Kittel melody against Kittel's basses and Bach's settings.
 *  With `leaveOut`, setting k is judged against Kittel's other basses only (Kittel's own benchmark). */
function measure(c: KittelChorale, sets: string[][], s: KStats, leaveOut = false) {
  const m = kittelMelody(c);
  const endIdx = new Set(phraseEnds(m).map((e) => e.index));
  c.notes.forEach((n, i) => {
    const kit = n.kittel.map((k) => k.chord);
    if (kit.includes("?")) return;
    const bach = n.bach.map((b) => b.chord);
    sets.forEach((ch, k) => {
      const ref = new Set([...bach, ...kit.filter((_, j) => !(leaveOut && j === k))]);
      const ok = ref.has(ch[i]) ? 1 : 0;
      s.attested += ok;
      s.n++;
      if (endIdx.has(i)) ((s.cadAttested += ok), s.cadN++);
      if (bach.length) ((s.bachSame += ch[i] === bach[0] ? 1 : 0), s.bachN++);
    });
    const gen = new Set(sets.map((ch) => ch[i]));
    const kd = new Set(kit);
    s.cover += [...kd].filter((x) => gen.has(x)).length / kd.size;
    s.coverN++;
    s.spread += gen.size;
    s.spreadN++;
  });
  s.plans += new Set(sets.map((ch) => [...endIdx].map((i) => ch[i]).join(" "))).size;
}

const gen = zero(),
  kit = zero(),
  indep = zero(),
  top = zero();
const examples: { c: KittelChorale; sets: Setting[] }[] = [];
const kModels: Models[] = KITTEL.map((c) => {
  const held = new Set(c.bachSettings);
  return trainModels(BACH.filter((b: BachChorale) => !held.has(b.no)));
});
for (const [ci, c] of KITTEL.entries()) {
  const models = kModels[ci];
  const m = kittelMelody(c);
  const nb = kittelBasses(c);
  const sets = diverseSettings(models, m, nb, rng(1000 + c.number));
  measure(c, sets.map((s) => s.chords), gen);
  measure(c, [bestSetting(models, m).chords], top);
  measure(c, Array.from({ length: nb }, (_, k) => c.notes.map((n) => n.kittel[k].chord)), kit, true);
  const r = rng(2000 + c.number);
  const ind = Array.from({ length: nb }, () => m.notes.map((n) => draw(models.harmony.step(m.mode, n.deg, "start"), r())));
  measure(c, ind, indep);
  if (c.number === 1 || c.number === 7) examples.push({ c, sets });
}

say("## 2. Kittel's 24 melodies: eight settings each, beside his eight basses");
say();
say("For each melody the generator makes as many settings as Kittel has basses (8, or 9), trained on Bach's");
say("chorales without Bach's settings of that tune; Kittel's basses are never trained on. A chord is *attested*");
say("when Kittel or Bach puts the same chord under that note. Kittel's own basses are measured the same way,");
say("each against his other basses and Bach (the benchmark: what a master's set of variants looks like).");
say();
say("| | chords attested | at phrase ends | Bach's chord (where Bach set the tune) | Kittel's chords found | different chords per note | different cadence plans |");
say("|---|---|---|---|---|---|---|");
const row = (name: string, s: KStats) =>
  say(
    `| ${name} | ${pct(s.attested, s.n)} | ${pct(s.cadAttested, s.cadN)} | ${pct(s.bachSame, s.bachN)} | ${pct(s.cover, s.coverN)} | ${(s.spread / s.spreadN).toFixed(1)} | ${(s.plans / KITTEL.length).toFixed(1)} |`,
  );
row("**Kittel's basses** (each against the others)", kit);
row("**generator**, diverse settings", gen);
row("generator, its single most likely setting", top);
row("baseline: each chord drawn alone from Bach's habit at the melody degree", indep);
say();
say("Columns: *Kittel's chords found*: the share of the distinct chords Kittel uses under a note that one of the");
say("generated settings also uses. *Different chords per note*: across the eight. *Different cadence plans*:");
say("among the eight, per melody.");
say();

say("**Variety against attestation.** The more the settings differ, the more of their chords neither master uses.");
say("The generator's two settings (temperature T of the draws, the share of the likelier draws kept) trace the trade-off;");
say("the default (T = 0.8, half kept) is the point with Kittel's variety. These two numbers, and the weight of a");
say("different cadence when the eight are chosen (3 chords: it gives Kittel's 4.6 cadence plans per melody, where 1 gives");
say("3.7, at no cost in attestation), are the only ones chosen by looking at Kittel's basses.");
say();
say("| T | kept | chords attested | Kittel's chords found | different chords per note |");
say("|---|---|---|---|---|");
for (const [T, keep] of [[0.5, 0.5], [0.65, 0.5], [0.8, 0.5], [1, 0.5], [1, 0.15]]) {
  const s = zero();
  KITTEL.forEach((c, ci) => measure(c, diverseSettings(kModels[ci], kittelMelody(c), kittelBasses(c), rng(1000 + c.number), { T, keep }).map((x) => x.chords), s));
  say(`| ${T} | ${keep} | ${pct(s.attested, s.n)} | ${pct(s.cover, s.coverN)} | ${(s.spread / s.spreadN).toFixed(1)} |`);
}
say(`| *Kittel* | | ${pct(kit.attested, kit.n)} | 100% | ${(kit.spread / kit.spreadN).toFixed(1)} |`);
say();

say("## 3. Two examples");
for (const { c, sets } of examples) {
  say();
  say(`### Kittel No. ${c.number}, *${c.title}* (${c.tonic} ${c.mode})`);
  say();
  const head = c.notes.map((n) => `${n.degree}${n.fermata ? "𝄐" : ""}`);
  say(`| | ${head.join(" | ")} |`);
  say(`|---|${head.map(() => "---").join("|")}|`);
  for (let k = 0; k < kittelBasses(c); k++) say(`| Kittel ${c.notes[0].kittel[k].bass} | ${c.notes.map((n) => n.kittel[k].chord).join(" | ")} |`);
  if (c.notes.some((n) => n.bach.length)) say(`| Bach ${c.notes.find((n) => n.bach.length)!.bach[0].no} | ${c.notes.map((n) => n.bach[0]?.chord ?? "").join(" | ")} |`);
  sets.forEach((s, k) => say(`| gen. ${k + 1} | ${s.chords.map((ch, i) => (c.notes[i].kittel.some((x) => x.chord === ch) || c.notes[i].bach.some((x) => x.chord === ch) ? ch : `**${ch}**`)).join(" | ")} |`));
  say();
  say("The top row is the melody as scale degrees (𝄐 a fermata). In the generated rows, a chord in bold is used");
  say("under that note by neither Kittel nor Bach.");
}

