/**
 * Motive and imitation in Bach's 370 chorales (src/chorale/generate/motives.ts), each measured against
 * chance:
 *   - imitation: the share of figures answered by another voice within two bars, against the share
 *     answered as far away, two bars long, four to six bars later (local answering beyond the
 *     chorale's general vocabulary of figures);
 *   - pre-imitation: a lower voice stating the opening of the melody's next phrase in the bar before it,
 *     against the same test with another chorale's phrase opening;
 *   - motivic unity: how often a figure of diminution recurs in its own chorale, against how often it
 *     occurs in another chorale of the same meter with as many figures;
 *   - chromatic lines in every voice, and how often another voice answers one within two bars.
 *
 * Output: docs/chorales/MOTIVES.md, data/chorales/generator/motives.json.
 * Run:  node tools/chorales/motives_report.ts
 */
import { writeFileSync } from "node:fs";
import { STUDY } from "../../src/chorale/generate/diminution.ts";
import { answeredShare, chromaticLines, figures, imitations, phraseStarts, preImitations } from "../../src/chorale/generate/motives.ts";
import { realise, type Note } from "../../src/chorale/level6.ts";
import { BACH } from "../../src/chorale/generate/corpus.ts";
import { VoiceModel } from "../../src/chorale/generate/voices.ts";
import { DiminutionModel, bachAligned, diminish } from "../../src/chorale/generate/diminution.ts";
import { rng } from "../../src/counterpoint/choices/cantus.ts";

const VOICE = ["soprano", "alto", "tenor", "bass"];
const bar = (meter: string) => {
  const [a, b] = meter.split("/").map(Number);
  return (32 * a) / b;
};
const pct = (a: number, b: number) => `${b ? ((100 * a) / b).toFixed(1) : "0"}%`;
const CS = STUDY.chorales;
const lines: string[] = [];
const say = (s = "") => {
  lines.push(s);
  console.log(s);
};
const json: Record<string, unknown> = { generated_by: "tools/chorales/motives_report.ts" };

say("# Motive and imitation in Bach's chorales");
say();
say("Generated by `node tools/chorales/motives_report.ts` (`src/chorale/generate/motives.ts`), on the four voices of the 370 chorales");
say("as the study data has them (data/chorales/study.json: every note, embellishments included). The owner's note on the second");
say("ratings asks whether Bach is to be read motivically and imitatively too, not only chord by chord. Each measure below is set");
say("against chance, since in four voices built from the same scale and the same few rhythms figures recur anyway.");
say();
say("A *figure* is four notes of one voice, without a rest or a fermata inside: the lengths of its first three notes and its three");
say("intervals counted in letters (a tonal answer: a third is a third, major or minor). Scale fragments (every interval a step or");
say("a repeat) are left out of the imitation measures: they recur by chance far more than shaped figures.");
say();

// ---- imitation ----
const imit: Record<string, { figures: number; near: number; far: number }> = {};
for (const kind of ["shaped", "quick", "shaped, no quick"]) imit[kind] = { figures: 0, near: 0, far: 0 };
const filters: Record<string, (f: ReturnType<typeof figures>[number]) => boolean> = {
  shaped: (f) => !f.plain,
  quick: (f) => !f.plain && f.quick,
  "shaped, no quick": (f) => !f.plain && !f.quick,
};
const answers = new Map<string, number>();
const intervals = new Map<number, number>();
let imitTotal = 0;
for (const c of CS) {
  const B = bar(c.meter);
  for (const [k, f] of Object.entries(filters)) {
    const near = answeredShare(c.voices as Note[][], 0, 2 * B, 4, f);
    const far = answeredShare(c.voices as Note[][], 4 * B, 6 * B, 4, f);
    imit[k].figures += near.figures;
    imit[k].near += near.answered;
    imit[k].far += far.answered;
  }
  for (const x of imitations(c.voices as Note[][], 2 * B)) {
    imitTotal++;
    const key = `${VOICE[x.first.voice]} → ${VOICE[x.answer.voice]}`;
    answers.set(key, (answers.get(key) ?? 0) + 1);
    intervals.set(x.interval, (intervals.get(x.interval) ?? 0) + 1);
  }
}
say("## Imitation");
say();
say("The share of figures that another voice states again (same rhythm, same intervals in letters, from any degree) within two");
say("bars after, against the share stated again two bars long but four to six bars after: the excess is answering, the rest the");
say("chorale's general vocabulary.");
say();
say("| figures | count | answered within 2 bars | answered 4-6 bars later | ratio |");
say("|---|---|---|---|---|");
for (const [k, x] of Object.entries(imit)) say(`| ${k} | ${x.figures} | ${pct(x.near, x.figures)} | ${pct(x.far, x.figures)} | ${(x.near / Math.max(1, x.far)).toFixed(2)} |`);
say();
const ivName = ["unison or octave", "second", "third", "fourth", "fifth", "sixth", "seventh"];
say(`Between which voices (${imitTotal} pairs of a shaped figure and an answer within two bars): ${[...answers].sort((a, b) => b[1] - a[1]).slice(0, 8).map(([k, v]) => `${k} ${pct(v, imitTotal)}`).join(", ")}.`);
say();
say(`At which interval (in letters, up from the first statement): ${[...intervals].sort((a, b) => b[1] - a[1]).map(([k, v]) => `${ivName[k]} ${pct(v, imitTotal)}`).join(", ")}.`);
say();
json.imitation = { imit, answers: Object.fromEntries(answers), intervals: Object.fromEntries(intervals) };

// ---- pre-imitation ----
let phrases = 0,
  pre = 0,
  preBase = 0;
const preVoices = new Map<number, number>();
const preExamples: string[] = [];
const bySig = (c: (typeof CS)[number]) => c.voices as Note[][];
CS.forEach((c, ci) => {
  const B = bar(c.meter);
  const v = bySig(c);
  const n = phraseStarts(v[0]).length - 1;
  phrases += n;
  const found = preImitations(v, B);
  pre += new Set(found.map((x) => x.phrase)).size;
  for (const x of found) preVoices.set(x.voice, (preVoices.get(x.voice) ?? 0) + 1);
  if (found.length && preExamples.length < 12) preExamples.push(`no. ${c.n} (${VOICE[found[0].voice]}, phrase ${found[0].phrase + 1})`);
  // chance: another chorale's melody (same meter) over this chorale's lower voices, its phrases
  // placed at this chorale's phrase starts
  const o = CS[(ci + 37) % CS.length];
  const ov = bySig(o)[0];
  const starts = phraseStarts(v[0]).slice(1);
  const oStarts = phraseStarts(ov).slice(1);
  const fake: Note[] = [];
  starts.forEach((s, p) => {
    const os = oStarts[p % Math.max(1, oStarts.length)];
    if (os === undefined) return;
    const shift = v[0][s][0] - ov[os][0];
    if (fake.length) {
      const l = fake[fake.length - 1];
      fake[fake.length - 1] = [l[0], l[1], l[2], 1];
    }
    for (let k = os; k < Math.min(ov.length, os + 4); k++) fake.push([ov[k][0] + shift, ov[k][1], ov[k][2]]);
  });
  if (fake.length) {
    // a soprano made of the other chorale's phrase openings, each preceded by a fermata
    const sop: Note[] = [[0, 1, v[0][0][2], 1], ...fake.filter((x) => x[0] > 0)];
    preBase += new Set(preImitations([sop, v[1], v[2], v[3]], B).map((x) => x.phrase)).size;
  }
});
say("## Pre-imitation of the melody");
say();
say("A lower voice stating the opening of the melody's next phrase (its first four notes, intervals in letters, rhythm free) in");
say("the bar before the phrase begins. Chance: the same test with another chorale's phrase openings set at this chorale's");
say("phrase starts.");
say();
say(`- Phrases (after the first): ${phrases}. Pre-imitated: ${pre} (${pct(pre, phrases)}); by chance: ${preBase} (${pct(preBase, phrases)}).`);
say(`- In which voice: ${[...preVoices].sort((a, b) => b[1] - a[1]).map(([k, v]) => `${VOICE[k]} ${v}`).join(", ")}.`);
say(`- For instance: ${preExamples.join(", ")}.`);
say();
json.preImitation = { phrases, pre, preBase, voices: Object.fromEntries(preVoices) };

// ---- motivic unity ----
/** Within a chorale against another of the same meter: the share of its figures of diminution (in the
 *  alto, tenor and bass) that recur in it, and the share found among as many figures of the other. */
export function unityOf(mine: string[], other: string[]) {
  const count = new Map<string, number>();
  for (const f of mine) count.set(f, (count.get(f) ?? 0) + 1);
  const o = new Set<string>();
  for (let k = 0; k < mine.length && other.length; k++) o.add(other[k % other.length]);
  return { within: mine.filter((f) => count.get(f)! > 1).length, across: mine.filter((f) => o.has(f)).length, top: [...count].sort((x, y) => y[1] - x[1])[0] };
}
const sameMeter = new Map<string, (typeof CS)[number][]>();
for (const c of CS) sameMeter.set(c.meter, [...(sameMeter.get(c.meter) ?? []), c]);
say("## Motivic unity of the diminution");
say();
say("The figures of diminution (a figure with a note shorter than a quarter) in the alto, tenor and bass: how often one recurs in");
say("its own chorale, against how often it occurs among as many figures of another chorale in the same meter. *Shaped*: scale");
say("fragments left out (running notes recur everywhere).");
say();
const unityJson: Record<string, unknown> = {};
for (const [name, keep] of [
  ["all", (f: ReturnType<typeof figures>[number]) => f.quick && f.voice > 0],
  ["shaped", (f: ReturnType<typeof figures>[number]) => f.quick && !f.plain && f.voice > 0],
] as const) {
  let within = 0,
    across = 0,
    tokens = 0;
  const unity: { n: number; within: number; across: number; top: string; topCount: number }[] = [];
  const of = (c: (typeof CS)[number]) => figures(c.voices as Note[][]).filter(keep).map((f) => f.tonal);
  for (const c of CS) {
    const fs = of(c);
    if (fs.length < 4) continue;
    const peers = sameMeter.get(c.meter)!.filter((o) => o.n !== c.n);
    const u = unityOf(fs, of(peers[c.n % peers.length]));
    within += u.within;
    across += u.across;
    tokens += fs.length;
    unity.push({ n: c.n, within: u.within / fs.length, across: u.across / fs.length, top: u.top[0], topCount: u.top[1] });
  }
  const better = unity.filter((u) => u.within > u.across).length;
  say(`- ${name === "all" ? "All figures of diminution" : "Shaped figures of diminution"}: ${tokens}. Recurring in their own chorale: ${pct(within, tokens)}; found in another chorale of the same meter: ${pct(across, tokens)}. Chorales whose figures recur in them more: ${better} of ${unity.length}.`);
  if (name === "shaped") {
    const most = [...unity].sort((a, b) => b.within - b.across - (a.within - a.across)).slice(0, 8);
    say(`- The most unified, shaped figures (own recurrence against another's): ${most.map((u) => `no. ${u.n} (${(100 * u.within).toFixed(0)}% against ${(100 * u.across).toFixed(0)}%; its commonest figure ${u.top.replace("|", " | ")} ×${u.topCount})`).join("; ")}.`);
  }
  unityJson[name] = { tokens, within, across, better, chorales: unity.length };
}
say("- Figures are written as lengths (32nds) | intervals (letters).");
say();
json.unity = unityJson;

// ---- chromatic lines ----
let chrom = 0,
  chromAnswered = 0;
const chromVoices = new Map<number, number>();
const chromExamples: string[] = [];
for (const c of CS) {
  const B = bar(c.meter);
  const ls = chromaticLines(c.voices as Note[][]);
  for (const l of ls) {
    chrom++;
    chromVoices.set(l.voice, (chromVoices.get(l.voice) ?? 0) + 1);
    if (ls.some((m) => m.voice !== l.voice && m.at > l.at && m.at - l.at <= 2 * B)) {
      chromAnswered++;
      if (chromExamples.length < 10) chromExamples.push(`no. ${c.n} (${VOICE[l.voice]} then ${VOICE[ls.find((m) => m.voice !== l.voice && m.at > l.at && m.at - l.at <= 2 * B)!.voice]})`);
    }
  }
}
say("## Chromatic lines in every voice");
say();
say("Three or more semitone steps one way in a voice, at least one of them chromatic (the same letter altered), every note");
say("counted (the catalogue's chromatic bass lines count the bass on the beats only).");
say();
say(`- ${chrom} lines; in the soprano ${chromVoices.get(0) ?? 0}, alto ${chromVoices.get(1) ?? 0}, tenor ${chromVoices.get(2) ?? 0}, bass ${chromVoices.get(3) ?? 0}.`);
say(`- Answered by a chromatic line in another voice within two bars: ${chromAnswered} (${pct(chromAnswered, chrom)}). For instance: ${chromExamples.join(", ")}.`);
say();
json.chromatic = { lines: chrom, answered: chromAnswered, voices: Object.fromEntries(chromVoices) };

// ---- the generator's diminution against Bach's ----
// Bach's reduced chorales (one chord per beat, as the generator writes) embellished by the generator,
// each fifth of the tunes held out in turn, against Bach's own embellishments on the same chords
// written the same way (level6.ts realise): the figures of diminution, their recurrence, their answers.
const vm = new VoiceModel(BACH);
const tuneOf = new Map(BACH.map((b) => [b.no, b.tune]));
const tunes = [...new Set(BACH.map((b) => b.tune))].sort();
const gen: Record<string, number[]> = { "Bach": [0, 0, 0, 0, 0], "generator, as learnt": [0, 0, 0, 0, 0], "generator, with restraint (default)": [0, 0, 0, 0, 0] };
for (let fold = 0; fold < 5; fold++) {
  const held = new Set(tunes.filter((_, i) => i % 5 === fold));
  const dm = new DiminutionModel(CS.filter((c) => !held.has(tuneOf.get(c.n) ?? "")), { parallel: vm.parallel, augSecond: vm.augSecond });
  for (const c of CS) {
    if (!held.has(tuneOf.get(c.n) ?? "")) continue;
    const b = BACH.find((x) => x.no === c.n);
    const al = b ? bachAligned(c, b) : null;
    if (!al) continue;
    const B = bar(c.meter);
    const sets: [string, Note[][]][] = [
      ["Bach", al.lines.map((l, v) => (v === 0 ? l : realise(l, al.bach[v], c.sig)))],
      ["generator, as learnt", diminish(dm, al.lines, c.sig, rng(c.n), 1, [true, true, true], [0, 0, 0]).lines],
      ["generator, with restraint (default)", diminish(dm, al.lines, c.sig, rng(c.n), 1).lines],
    ];
    for (const [k, v] of sets) {
      const fs = figures(v).filter((f) => f.quick && !f.plain && f.voice > 0).map((f) => f.tonal);
      const cnt = new Map<string, number>();
      for (const f of fs) cnt.set(f, (cnt.get(f) ?? 0) + 1);
      const near = answeredShare(v, 0, 2 * B, 4, (f) => !f.plain && f.quick);
      const far = answeredShare(v, 4 * B, 6 * B, 4, (f) => !f.plain && f.quick);
      const x = gen[k];
      x[0] += fs.filter((f) => cnt.get(f)! > 1).length;
      x[1] += fs.length;
      x[2] += near.answered;
      x[3] += far.answered;
      x[4] += near.figures;
    }
  }
}
say("## The generator's diminution against Bach's");
say();
say("Bach's chorales reduced and read one chord per beat, as the generator writes; embellished by the generator (each fifth of");
say("the tunes held out in turn), against Bach's own embellishments on the same chords written the same way (level 6's");
say("figures). Shaped figures of diminution in the alto, tenor and bass.");
say();
say("| | shaped figures | recurring in their chorale | answered within 2 bars | answered 4-6 bars later | ratio |");
say("|---|---|---|---|---|---|");
for (const [k, x] of Object.entries(gen)) say(`| ${k} | ${x[1]} | ${pct(x[0], x[1])} | ${(100 * x[2] / x[4]).toFixed(2)}% | ${(100 * x[3] / x[4]).toFixed(2)}% | ${(x[2] / Math.max(1, x[3])).toFixed(1)} |`);
say();
json.generator = gen;

// ---- what it says ----
const sh = (json.unity as Record<string, { tokens: number; within: number; across: number }>).shaped;
const gq = imit.quick;
const G = gen["Bach"],
  R = gen["generator, with restraint (default)"];
say("## What it says");
say();
say(`- **Motivic unity is real.** A chorale's shaped figures of diminution recur in it ${pct(sh.within, sh.tokens)} of the time, against`);
say(`  ${pct(sh.across, sh.tokens)} in another chorale of the same meter: each chorale has its own small vocabulary of figures.`);
say(`- **Imitation is real but local and modest.** A figure of diminution is answered by another voice within two bars ${pct(gq.near, gq.figures)}`);
say(`  of the time, against ${pct(gq.far, gq.figures)} as far away; mostly between tenor and bass, and at any interval (the octave and the`);
say("  fourth a little more often than the rest): a figure passed through the texture, not the imitation of a subject at the fifth.");
say(`- **There is no pre-imitation of the melody** in these four-part settings (${pct(pre, phrases)} of phrases against ${pct(preBase, phrases)} by chance):`);
say("  the chorale preludes' device does not belong to the cantional setting.");
say(`- **Chromatic lines live in the bass** (${chromVoices.get(3) ?? 0} of ${chrom}) and are seldom answered by another voice (${pct(chromAnswered, chrom)}): Bach's chromaticism`);
say("  in the chorales is a bass's line under the harmony more than a motive passed between the voices.");
say(`- **The generator** writes too many figures as learnt; with the calibrated restraint (step 5's default) its density and the`);
say(`  recurrence of its figures come to Bach's (${R[1]} figures and ${pct(R[0], R[1])} recurring, against ${G[1]} and ${pct(G[0], G[1])}). What it lacks is`);
say(`  Bach's *locality*: his figures, when they come back, come back nearby (answered near ${(G[2] / Math.max(1, G[3])).toFixed(1)} times as often as far), the`);
say(`  generator's anywhere (${(R[2] / Math.max(1, R[3])).toFixed(1)} times). Three simple devices tried in the diminution chain left this unchanged (11`);
say("  October 2026: a preference for the kind another voice made on the chord before; for the same kind on the same move,");
say("  which is the same figure; a figure of the phrase, one kind favoured through each phrase). Bach's figures belong to");
say("  passages (a sequence in the melody, a line of the text); a generator that has them will need to plan a passage's");
say("  figure and its answers, which is the fugue's craft (Phase B: subject, answer, sequence), rather than choose note by");
say("  note.");
say();

writeFileSync(new URL("../../docs/chorales/MOTIVES.md", import.meta.url), lines.join("\n") + "\n");
writeFileSync(new URL("../../data/chorales/generator/motives.json", import.meta.url), JSON.stringify(json, null, 1) + "\n");
