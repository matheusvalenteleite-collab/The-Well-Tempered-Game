/**
 * Local keys in Bach's 370 chorales (src/chorale/generate/keys.ts): the checks of the reading, the
 * regions by degree of the home key, and how many chords are diatonic, applied (a dominant or a
 * leading-tone chord of a degree, going to it) or chromatic in their local key.
 *
 * Output: docs/chorales/KEYS.md and data/chorales/generator/local-keys.json (for every chorale, every
 * on-beat event of bach-events.json: [local tonic, mode, chord in the local key, "d" diatonic | "a:ii"
 * applied to ii | "c" chromatic]).
 *
 * Run:  node tools/chorales/keys_report.ts
 */
import { writeFileSync } from "node:fs";
import { BACH } from "../../src/chorale/generate/corpus.ts";
import { keyDegree, localKeys, WEIGHTS } from "../../src/chorale/generate/keys.ts";
import { thirty, barAt } from "./exceptions_lib.ts";

const lines: string[] = [];
const say = (s = "") => {
  lines.push(s);
  console.log(s);
};
const pct = (a: number, b: number) => `${b ? ((100 * a) / b).toFixed(1) : "0"}%`;
const roman = (s: string) => s.replace(/^b/, "♭").replace(/^#/, "♯");

// ---- the checks ----
function stats(w = WEIGHTS) {
  let ends = 0,
    onI = 0,
    onV = 0,
    changes = 0,
    events = 0,
    diatonic = 0,
    applied = 0,
    startHome = 0;
  for (const c of BACH) {
    const k = localKeys(c, w);
    if (keyDegree(c, k[0]).toUpperCase() === "I") startHome++;
    k.forEach((x, i) => {
      events++;
      if (x.diatonic) diatonic++;
      else if (x.applied) applied++;
      if (i && (x.pc !== k[i - 1].pc || x.mode !== k[i - 1].mode)) changes++;
      if (c.notes[i].end) {
        ends++;
        if (/^(I|i)$/.test(x.chord)) onI++;
        else if (x.chord === "V") onV++;
      }
    });
  }
  return { ends, onI, onV, changes, events, diatonic, applied, startHome };
}

const s = stats();
say("# Local keys in Bach's chorales");
say();
say("Generated by `node tools/chorales/keys_report.ts` from `src/chorale/generate/keys.ts`. The owner's second ratings");
say("(docs/chorales/LICENCES-RATINGS.md) flagged two chords read against the chorale's home key where the local key (no. 132,");
say("bar 23: VI of D minor, not ♭II of A minor) or the mode (no. 205, bar 7: the Phrygian second) governs. Every chord is now");
say("read in its local key as well.");
say();
say("## The reading");
say();
say("Two levels, as an analyst reads them:");
say();
say("- **Regions**: a hidden Markov chain over the 24 keys, one state per on-beat chord, decoded by Viterbi. A region's key");
say("  must be confirmed by a close: a phrase may be in the home key, or in a key whose tonic or dominant ends it or ends the");
say("  phrase before (a modulation starts in one phrase and closes in the next). Within those, a key is told by the pitches");
say("  sounding (Temperley's key profiles), by whether the chord belongs to it (the melodic minor's chords too), by a dominant");
say("  going to its tonic, and by a phrase end on its tonic or dominant; against a cost for changing key and for keys far");
say("  from home by the circle of fifths. The chain starts at home and ends at home (a chorale ending on the dominant ends");
say("  with a half or a Phrygian close, not in the dominant's key).");
say("- **Tonicisations** inside a region: a chord outside the region's key that is a dominant (major, dominant seventh, or");
say("  the diminished seventh read as a dominant with a minor ninth) or a leading-tone chord (diminished) of a degree of the");
say("  key and goes to it is *applied* to that degree (V/ii, vii°/V). A minor key's tonic as a major chord at a phrase end");
say("  (the Picardy third) is in the key. What is left is *chromatic* in its local key: the licences' ground.");
say();
say(`Weights (set by hand): ${Object.entries(WEIGHTS).map(([k, v]) => `${k} ${v}`).join(", ")}.`);
say();
say("## Checks");
say();
say(`- Phrase ends on the local tonic: ${pct(s.onI, s.ends)}; on the local dominant (half closes): ${pct(s.onV, s.ends)}; together ${pct(s.onI + s.onV, s.ends)} of ${s.ends}.`);
say(`- Key changes: ${(s.changes / BACH.length).toFixed(2)} a chorale. The first chord in the home key in ${BACH.filter((c) => keyDegree(c, localKeys(c)[0]).toUpperCase() === "I").length} of 370 chorales (the others are read as beginning in the key of their first close).`);
say(`- Chords in their local key: ${pct(s.diatonic, s.events)} diatonic, ${pct(s.applied, s.events)} applied to a degree, ${pct(s.events - s.diatonic - s.applied, s.events)} chromatic, of ${s.events}.`);
say("- Robustness: the shares change little when a weight is halved or doubled:");
say();
say("| weights changed | ends on local I or V | key changes a chorale | diatonic |");
say("|---|---|---|---|");
for (const [name, w] of [
  ["none", {}],
  ["change 6", { change: 6 }],
  ["change 12", { change: 12 }],
  ["distance 0.3", { distance: 0.3 }],
  ["distance 1.2", { distance: 1.2 }],
  ["inKey 1, outKey -2", { inKey: 1, outKey: -2 }],
  ["dominant 0", { dominant: 0 }],
  ["tonicEnd 3", { tonicEnd: 3 }],
] as [string, Partial<typeof WEIGHTS>][]) {
  const x = stats({ ...WEIGHTS, ...w });
  say(`| ${name} | ${pct(x.onI + x.onV, x.ends)} | ${(x.changes / BACH.length).toFixed(2)} | ${pct(x.diatonic, x.events)} |`);
}
say();
say("- The owner's flags:");
for (const [no, at] of [
  [132, 704],
  [205, 216],
]) {
  const c = BACH.find((x) => x.no === no)!;
  const i = c.notes.findIndex((n) => thirty(n.t) === at);
  const k = localKeys(c)[i];
  say(`  - no. ${no} bar ${barAt(c, at)}: home ${c.tonic} ${c.edition_mode}; region ${k.tonic} ${k.mode} (${roman(keyDegree(c, k))} of home); the chord ${roman(k.chord)} there, ${k.diatonic ? "in the key" : k.applied ? `applied to ${k.applied}` : "chromatic"}.`);
}
say();

// ---- the regions ----
const regions = new Map<string, number>(),
  regionsMinor = new Map<string, number>();
let evMajor = 0,
  evMinor = 0;
for (const c of BACH)
  for (const k of localKeys(c)) {
    const m = c.mode === "major" ? regions : regionsMinor;
    m.set(keyDegree(c, k), (m.get(keyDegree(c, k)) ?? 0) + 1);
    if (c.mode === "major") evMajor++;
    else evMinor++;
  }
say("## The regions");
say();
say("Share of the chords in each region, by the region's key as a degree of home (upper case major, lower case minor).");
say();
const top = (m: Map<string, number>, n: number) =>
  [...m]
    .sort((a, b) => b[1] - a[1])
    .slice(0, 9)
    .map(([k, v]) => `${roman(k)} ${pct(v, n)}`)
    .join(", ");
say(`- Major chorales: ${top(regions, evMajor)}.`);
say(`- Minor chorales (the Dorian and Phrygian among them): ${top(regionsMinor, evMinor)}.`);
say();

// ---- the chromatic chords ----
const chrom = new Map<string, number>(),
  app = new Map<string, number>();
for (const c of BACH)
  localKeys(c).forEach((k, i) => {
    if (k.applied) {
      const key = `${k.mode}: ${/^(major$|dominant|seventh)/.test(c.notes[i].kind) ? "V" : "vii°"}/${k.applied}`;
      app.set(key, (app.get(key) ?? 0) + 1);
    } else if (!k.diatonic) {
      const key = `${k.mode}: ${k.chord} (${c.notes[i].kind})`;
      chrom.set(key, (chrom.get(key) ?? 0) + 1);
    }
  });
say("## Applied and chromatic chords");
say();
say(`Applied (the most common): ${[...app].sort((a, b) => b[1] - a[1]).slice(0, 10).map(([k, v]) => `${roman(k)} ${v}`).join(", ")}.`);
say();
say(`Chromatic in the local key (the most common): ${[...chrom].sort((a, b) => b[1] - a[1]).slice(0, 14).map(([k, v]) => `${roman(k)} ${v}`).join(", ")}.`);
say();
say("Chromatic chords that do not go where an applied chord would (an applied dominant left unresolved, mixture, the flat");
say("second) are the ground of the narrowed licence catalogue (docs/chorales/LICENCES.md).");
writeFileSync(new URL("../../docs/chorales/KEYS.md", import.meta.url), lines.join("\n") + "\n");
writeFileSync(
  new URL("../../data/chorales/generator/local-keys.json", import.meta.url),
  JSON.stringify({
    generated_by: "tools/chorales/keys_report.ts",
    fields: ["tonic", "mode", "chord in the local key", "d diatonic | a:<degree> applied | c chromatic"],
    chorales: BACH.map((c) => ({ no: c.no, keys: localKeys(c).map((k) => [k.tonic, k.mode, k.chord, k.diatonic ? "d" : k.applied ? `a:${k.applied}` : "c"]) })),
  }) + "\n",
);
