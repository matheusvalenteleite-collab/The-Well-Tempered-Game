/**
 * Step 4 of the chorale generator, the alto and tenor (src/chorale/generate/voices.ts): how good, by
 * the game's own judge (src/chorale/level5.ts) and against Bach.
 *
 *  1. Bach's chorales, his soprano, bass and chords given (every setting of the tune held out from
 *     what the search learns): is the generated alto and tenor his?
 *  2. Kittel's 194 figured basses (level 5's slots): the judge's findings, beside Bach's own inner
 *     voices read the same way; agreement with Bach's settings where his bass is Kittel's.
 *  3. The generator's own settings of Kittel's melodies (steps 1-3, data/chorales/generator/
 *     kittel-settings.json from tools/chorales/generator_report.ts), made four-part.
 * Each with the search's habit costs on, and off (smooth voice-leading and the two gravest warnings
 * only), to show what Bach's habits add.
 *
 * Output: docs/chorales/GENERATOR-VOICES.md; data/chorales/generator/satb.json (the four-part
 * settings, for tools/chorales/generator_musicxml.py).   Run:  node tools/chorales/voices_report.ts
 */
import { readFileSync, writeFileSync } from "node:fs";
import { BACH, KITTEL } from "../../src/chorale/generate/corpus.ts";
import { VoiceModel, innerVoices, type VoiceOptions, VOICING, writeVoices } from "../../src/chorale/generate/voices.ts";
import { bachSlots, settingSlots } from "../../src/chorale/generate/slots.ts";
import { midiOf, type FigureRow } from "../../src/chorale/generate/theory.ts";
import { LEVEL5, compareBach, judge, type Finding, type Slot } from "../../src/chorale/level5.ts";
import type { Setting } from "../../src/chorale/generate/index.ts";

const pct = (a: number, b: number) => `${b ? Math.round((100 * a) / b) : 0}%`;
const out: string[] = [];
const say = (s = "") => {
  out.push(s);
  console.log(s);
};
const ON: VoiceOptions = VOICING;
const OFF: VoiceOptions = { habits: 0 };

// What the judge says, per 100 slots, by kind of finding.
const KEYS = ["parallel", "contrary", "augSecond", "missing", "foreign", "noFifth", "doubling", "spacing", "crossing", "range", "seventh", "leading"];
type Tally = { slots: number; f: Record<string, number> };
const tally = (): Tally => ({ slots: 0, f: {} });
function add(t: Tally, slots: Slot[], fs: Finding[]) {
  t.slots += slots.length;
  for (const x of fs) t.f[x.key] = (t.f[x.key] ?? 0) + 1;
}
const per100 = (t: Tally, k: string) => ((100 * (t.f[k] ?? 0)) / t.slots).toFixed(1);

// ---- 1. Bach held out ----
const tunes = [...new Set(BACH.map((c) => c.tune))];
const bachRes = { on: { a: 0, t: 0, pair: 0 }, off: { a: 0, t: 0, pair: 0 }, n: 0, chorales: 0, skipped: 0, failed: 0 };
const bachOwn = tally(),
  bachGen = tally();
const vmAll = new VoiceModel(BACH);
const pcPair = (a: string, b: string) => [midiOf(a) % 12, midiOf(b) % 12].sort().join();
for (const t of tunes) {
  const vm = new VoiceModel(BACH.filter((c) => c.tune !== t));
  for (const c of BACH.filter((c) => c.tune === t)) {
    const sl = bachSlots(c);
    if (!sl || c.notes.some((n) => !n.a || !n.tn)) {
      bachRes.skipped++;
      continue;
    }
    const on = writeVoices(vm, sl, ON),
      off = innerVoices(vm, sl, undefined, 1, OFF);
    if (!on || !off) {
      bachRes.failed++;
      continue;
    }
    bachRes.chorales++;
    add(bachOwn, sl, judge(sl, c.notes.map((n) => n.a), c.notes.map((n) => n.tn)));
    add(bachGen, sl, judge(sl, on.alto, on.tenor));
    c.notes.forEach((n, i) => {
      bachRes.n++;
      for (const [k, v] of [["on", on], ["off", off]] as const) {
        bachRes[k].a += midiOf(v.alto[i]) === midiOf(n.a!) ? 1 : 0;
        bachRes[k].t += midiOf(v.tenor[i]) === midiOf(n.tn!) ? 1 : 0;
        bachRes[k].pair += pcPair(v.alto[i], v.tenor[i]) === pcPair(n.a!, n.tn!) ? 1 : 0;
      }
    });
  }
}

say("# The chorale generator, step 4: the alto and tenor");
say();
say("Generated by `node tools/chorales/voices_report.ts`. Code: `src/chorale/generate/voices.ts` (the search) and");
say("`slots.ts`; the judge is the game's own (`src/chorale/level5.ts`), and so are the habit tables the search is costed by.");
say("Under every chord, every (alto, tenor) that completes it in the voices' ranges; each choice and each move costs");
say("-log2 of how often Bach makes it; the voices are the cheapest path through the chorale. There are no errors (C21,");
say("the owner, 11 October 2026): the judge's warnings have three gravities, and the search costs each by its rarity in");
say("Bach, counted between chords that follow each other directly. Parallel fifths/octaves and augmented seconds are detected by the");
say("judge's own chord-to-chord check (level5.ts `findingsBetween`).");
say();
const vc = vmAll.counts;
say(`Bach, read so: ${vc.parallel} parallel fifths or octaves in a pair with an inner voice, in ${vc.pairsMoved} moving pairs`);
say(`(${vmAll.parallel.toFixed(1)} bits each), ${vc.contrary} by contrary motion (${vmAll.contrary.toFixed(1)} bits); ${vc.augSecond} augmented seconds in ${vc.innerMoves} moves of the alto and tenor (${vmAll.augSecond.toFixed(1)} bits);`);
say(`the fifth left out of ${vc.noFifth} of ${vc.triads} triads in 5/3 or 6 (${vmAll.noFifth.toFixed(1)} bits).`);
say();
say("## 1. Bach's chorales, his soprano, bass and chords given");
say();
say(`${bachRes.chorales} chorales (every setting of the tune held out from the moves the search learns; the level-5 habit tables are`);
say(`counted over all 370); ${bachRes.skipped} left out because an inner voice rests somewhere; ${bachRes.failed} where no voicing`);
say(`was found. ${bachRes.n} chords. Each chord as Kirnberger's reading gives it; where the bass is a passing note (263 chords),`);
say("its role says so and the chord's members all stand above it.");
say();
say("| | alto is Bach's | tenor is Bach's | alto and tenor sound Bach's two notes (any octave) |");
say("|---|---|---|---|");
say(`| **search, Bach's habits on** | ${pct(bachRes.on.a, bachRes.n)} | ${pct(bachRes.on.t, bachRes.n)} | ${pct(bachRes.on.pair, bachRes.n)} |`);
say(`| search, habits off (smooth voice-leading only) | ${pct(bachRes.off.a, bachRes.n)} | ${pct(bachRes.off.t, bachRes.n)} | ${pct(bachRes.off.pair, bachRes.n)} |`);
say();

// ---- 2. Kittel's figured basses ----
const kOn = tally(),
  kOff = tally();
const cmp = { on: { aligned: 0, sameBass: 0, same: 0 }, off: { aligned: 0, sameBass: 0, same: 0 } };
let kFail = 0,
  kBasses = 0;
const kittelSatb = new Map<number, { label: string; alto: string[]; tenor: string[] }[]>();
for (const c of Object.values(LEVEL5)) {
  const verses: { label: string; alto: string[]; tenor: string[] }[] = [];
  for (const b of c.basses) {
    kBasses++;
    const on = writeVoices(vmAll, b.slots, ON),
      off = innerVoices(vmAll, b.slots, undefined, 1, OFF);
    if (!on || !off) {
      kFail++;
      continue;
    }
    verses.push({ label: b.label, alto: on.alto, tenor: on.tenor });
    add(kOn, b.slots, judge(b.slots, on.alto, on.tenor));
    add(kOff, b.slots, judge(b.slots, off.alto, off.tenor));
    for (const s of c.bach)
      for (const [k, v] of [["on", on], ["off", off]] as const) {
        const r = compareBach(c, b.slots, v.alto, v.tenor, s);
        cmp[k].aligned += r.aligned;
        cmp[k].sameBass += r.sameBass;
        cmp[k].same += r.same;
      }
  }
  kittelSatb.set(c.number, verses);
}

// ---- 3. The generator's settings ----
const settings = JSON.parse(readFileSync(new URL("../../data/chorales/generator/kittel-settings.json", import.meta.url), "utf8")) as {
  chorales: { number: number; settings: { label: string; notes: { offset: string; pitch: string; degree: string; chord: string; position: string; figure: FigureRow[] }[] }[] }[];
};
const gOn = tally();
let gFail = 0,
  gN = 0;
const genSatb = new Map<number, { label: string; slots: Slot[]; alto: string[]; tenor: string[] }[]>();
for (const g of settings.chorales) {
  const c = KITTEL.find((x) => x.number === g.number)!;
  const k = { tonic: c.tonic, mode: c.mode };
  const end = `${LEVEL5[c.number].length}/32`;
  const verses: { label: string; slots: Slot[]; alto: string[]; tenor: string[] }[] = [];
  for (const st of g.settings) {
    gN++;
    const s = {
      chords: st.notes.map((n) => n.chord),
      bass: { degrees: st.notes.map((n) => n.degree), positions: st.notes.map((n) => n.position), pitches: st.notes.map((n) => n.pitch), figures: st.notes.map((n) => n.figure), midi: [] },
    } as unknown as Setting;
    const slots = settingSlots(s, k, c.notes.map((n) => ({ pitch: n.pitch, offset: n.offset })), end);
    const v = writeVoices(vmAll, slots, ON);
    if (!v) {
      gFail++;
      continue;
    }
    add(gOn, slots, judge(slots, v.alto, v.tenor));
    verses.push({ label: st.label, slots, alto: v.alto, tenor: v.tenor });
  }
  genSatb.set(g.number, verses);
}

say("## 2. The judge's findings, per 100 chords");
say();
say(`Kittel's ${kBasses} figured basses (level 5's slots, one per harmony; ${kFail} where no voicing was found); the generator's`);
say(`${gN} settings of his melodies (steps 1-3; ${gFail} without a voicing); and, for calibration, Bach's own alto and tenor on the`);
say("chorales of section 1, read by the same judge.");
say();
say(`| | ${KEYS.join(" | ")} |`);
say(`|---|${KEYS.map(() => "---").join("|")}|`);
say(`| *Bach's own inner voices* (${bachOwn.slots} chords) | ${KEYS.map((k) => per100(bachOwn, k)).join(" | ")} |`);
say(`| search on Bach's chorales (${bachGen.slots}) | ${KEYS.map((k) => per100(bachGen, k)).join(" | ")} |`);
say(`| **search on Kittel's basses** (${kOn.slots}) | ${KEYS.map((k) => per100(kOn, k)).join(" | ")} |`);
say(`| search on Kittel's basses, habits off | ${KEYS.map((k) => per100(kOff, k)).join(" | ")} |`);
say(`| **search on the generator's settings** (${gOn.slots}) | ${KEYS.map((k) => per100(gOn, k)).join(" | ")} |`);
say();
say("Keys (level5.ts, C21; gravity 3 grave, 2 warning, 1 note): *parallel* parallel fifths/octaves (3),");
say("*contrary* fifths/octaves by contrary motion (2); *augSecond* in an inner line; *missing*, *foreign* the chord the");
say("figure asks for; *noFifth*; *doubling*, *seventh*, *leading* where the choice is rare in Bach (under 5% in its context);");
say("*spacing*, *crossing*, *range*.");
say();
say("## 3. Beside Bach's settings of Kittel's melodies");
say();
say("Where one of Bach's settings of the tune (in Kittel's key) has a note under the same melody note and the same bass as");
say("Kittel's, do the generated alto and tenor sound Bach's two notes (level5.ts `compareBach`)?");
say();
say("| | chords compared | same two notes as Bach |");
say("|---|---|---|");
say(`| **search, habits on** | ${cmp.on.sameBass} | ${pct(cmp.on.same, cmp.on.sameBass)} |`);
say(`| search, habits off | ${cmp.off.sameBass} | ${pct(cmp.off.same, cmp.off.sameBass)} |`);
say();

say("## Reading");
say();
say("- **Bach's habits are what make the voices his.** With them, the generated alto and tenor are Bach's own notes");
say(`  ${pct(bachRes.on.a, bachRes.n)} and ${pct(bachRes.on.t, bachRes.n)} of the time, and sound his two notes ${pct(bachRes.on.pair, bachRes.n)} of the time; without them (the`);
say(`  smoothest voice-leading alone) about a third. Under Kittel's basses they sound the notes of Bach's own settings of the`);
say(`  tune ${pct(cmp.on.same, cmp.on.sameBass)} of the time (habits off: ${pct(cmp.off.same, cmp.off.sameBass)}).`);
say("- **The judge has little to say about them**: under 1 parallel fifth or octave per 100 chords, no augmented second,");
say("  the figure's chord complete; what remains is mostly a left-out fifth (which Bach also does) and the occasional rare");
say("  doubling or seventh. Where a voicing must break something (a melody note too low to leave room under it, a note the");
say("  figure adds that cannot be placed), the search crosses voices or leaves the added note out, and says so through the");
say("  judge's *crossing* and *missing*.");
say("- **Bach's own row is not a like-for-like calibration.** It reads his voices on the beat only: his suspensions,");
say("  appoggiaturas and passing notes on the beat count as *foreign* or *missing*, and two on-beat chords with notes moving");
say("  between them can count as parallels. The search writes chord tones only; the incidental notes are step 5.");
say("- Not yet: diminution (step 5); variety in the inner voices (the search can draw them as well as take the cheapest;");
say("  the four-part settings here take the cheapest).");

writeFileSync(new URL("../../docs/chorales/GENERATOR-VOICES.md", import.meta.url), out.join("\n") + "\n");

// ---- the four-part settings, for MusicXML ----
const notesOf = (slots: Slot[], ps: string[]) => slots.map((s, i) => [s.at, s.dur, ps[i]]);
writeFileSync(
  new URL("../../data/chorales/generator/satb.json", import.meta.url),
  JSON.stringify({
    generated_by: "tools/chorales/voices_report.ts",
    unit: "1/32 whole note",
    note: "Four-part settings of Kittel's melodies: 'generated' (steps 1-4: the generator's plan, chords, figured bass and inner voices) and 'kittel' (Kittel's own figured basses with generated inner voices). Notes [at, dur, pitch].",
    chorales: KITTEL.map((c) => {
      const l5 = LEVEL5[c.number];
      return {
        number: c.number,
        generated: (genSatb.get(c.number) ?? []).map((v) => ({
          label: v.label,
          alto: notesOf(v.slots, v.alto),
          tenor: notesOf(v.slots, v.tenor),
          bass: v.slots.map((s) => [s.at, s.dur, s.bass]),
          figures: v.slots.map((s, i) => [s.at, settings.chorales.find((g) => g.number === c.number)!.settings.find((x) => x.label === v.label)!.notes[i].figure]),
        })),
        kittel: (kittelSatb.get(c.number) ?? []).map((v) => {
          const b = l5.basses.find((x) => x.label === v.label)!;
          return { label: `Kittel ${v.label}`, alto: notesOf(b.slots, v.alto), tenor: notesOf(b.slots, v.tenor), bass: b.bass, printed: b.slots.map((s) => [s.at, s.printed]) };
        }),
      };
    }),
  }) + "\n",
);
