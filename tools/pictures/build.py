"""Renders the 48 fugue pictures and writes src/bench/pictures-data.ts (D383).

    python3 tools/pictures/build.py            # writes the data file
    python3 tools/pictures/sheet.py out.png    # a contact sheet

Each picture is cut to 4 bits a channel (#rgb, as emblem.ts has always drawn) and stored as its own
palette and a run-length string: a letter (a-z, A-Z) indexes the palette, digits after it repeat it.
"""
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
sys.path.insert(0, HERE)

from lib import W, H  # noqa: E402

ALPHA = "abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ"


def all_pictures():
    import book1
    out = dict(book1.PICTURES)
    try:
        import book2
        out.update(book2.PICTURES)
    except ImportError:
        pass
    return out


def q4(v):
    return min(15, max(0, int(round(v / 17))))


def quantise(p):
    """The picture as the game draws it: each channel to 4 bits."""
    im = p.im.convert("RGB")
    px = im.load()
    for y in range(H):
        for x in range(W):
            r, g, b = px[x, y]
            px[x, y] = (q4(r) * 17, q4(g) * 17, q4(b) * 17)
    return im


def encode(im):
    px = im.load()
    pal, idx = [], []
    for y in range(H):
        for x in range(W):
            r, g, b = px[x, y]
            c = "#%x%x%x" % (r // 17, g // 17, b // 17)
            if c not in pal:
                pal.append(c)
            idx.append(pal.index(c))
    if len(pal) > len(ALPHA):
        raise ValueError(f"{len(pal)} colours (at most {len(ALPHA)})")
    out, i = [], 0
    while i < len(idx):
        j = i
        while j < len(idx) and idx[j] == idx[i]:
            j += 1
        n = j - i
        out.append(ALPHA[idx[i]] + (str(n) if n > 1 else ""))
        i = j
    return pal, "".join(out)


def names():
    """The English names from fugue-names.ts (for the sheet)."""
    src = open(os.path.join(ROOT, "src/touch/fugue-names.ts"), encoding="utf8").read()
    out = {}
    for m in re.finditer(r'(wtc[12]f\d\d): \{ en: n\("([^"]+)"', src):
        out[m.group(1)] = {"en": m.group(2)}
    return out


def write():
    pics = all_pictures()
    lines = [
        "/**",
        " * D383: the 48 fugue pictures, generated by tools/pictures/build.py (do not edit by hand).",
        " * Each: its palette (#rgb) and its 64 x 40 pixels row by row, run-length coded (a letter indexes",
        " * the palette, a number after it repeats it). emblem.ts decodes them (pictureOf).",
        " */",
        "export const PICTURES: Readonly<Record<string, readonly [string, string]>> = {",
    ]
    total = 0
    for pid in sorted(pics):
        pal, rle = encode(quantise(pics[pid]()))
        total += len(rle)
        lines.append(f'  {pid}: ["{"".join(c[1:] for c in pal)}", "{rle}"],')
    lines.append("};")
    path = os.path.join(ROOT, "src/bench/pictures-data.ts")
    open(path, "w", encoding="utf8").write("\n".join(lines) + "\n")
    print(f"{len(pics)} pictures, {total} chars of pixels -> {path}")


if __name__ == "__main__":
    write()
